@dataclass(frozen=True, slots=True)
class Column:
    name: str
    type: SqlType
    public: bool = True


@dataclass(frozen=True, slots=True)
class Table:
    """`name` is the public name (the `r_` view's suffix and the compatibility view); `legacy` the v0.2.2 columns."""

    name: str
    columns: tuple[Column, ...]
    legacy: tuple[str, ...]

    @property
    def base(self) -> str:
        return f"m_{self.name}"

    @property
    def view(self) -> str:
        return f"r_{self.name}"

    @property
    def public(self) -> tuple[Column, ...]:
        return tuple(c for c in self.columns if c.public)


