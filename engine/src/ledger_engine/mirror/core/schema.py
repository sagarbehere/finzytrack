"""The mirror's SQL surface: its tables, their columns and the DDL that creates them (ADR-0015, ADR-0048; spec
design/specs/mirror/README.md "Three layers" and surface.toml). Pure: names and text only.

Three layers per table: the base table `m_<name>` (internal; every column), the public view `r_<name>` (the columns
documented for user SQL), and the compatibility view under the v0.2.2 name (exactly v0.2.2's columns, in v0.2.2's
order, read from `r_<name>`; `meta` has no public view and its compatibility view reads `m_meta`). Every view column
is a plain reference to a base column, so it keeps the column's declared type and affinity (README "Three layers").

This list is checked against `surface.toml` by `engine/tests/mirror/test_surface.py`, on the built file (BL-0057);
`python -I -m ledger_engine.mirror.core.schema` prints the DDL snapshot `contracts/mirror-ddl.sql`. Base tables carry
no keys, constraints or indexes: the spec asks for none, a uniqueness constraint lost lots in v0.2.2 and would refuse
legitimately shared TransactionIds (BL-0059); indexes come with the reads that need them (BL-0122).
"""

