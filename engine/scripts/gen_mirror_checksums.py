"""Print the mirror's per-table checksums over the corpus ledgers (BL-0057, S0096).

usage (cwd = the repository root, as `scripts/check_generated.py` runs it):
  engine/.venv/bin/python -I engine/scripts/gen_mirror_checksums.py --stdout > corpora/ledgers/mirror-checksums.json
  engine/.venv/bin/python -I engine/scripts/gen_mirror_checksums.py --rows CASE TABLE   # review one table's rows

The snapshot is a change detector: per corpus root and table, the row count and the SHA-256 of the normalized rows
(`engine/tests/mirror/checksums.py` has the corpus roots, the normalization and the rules). When a change to the
engine, its lockfile or the corpus changes a checksum, regenerate the file in the same commit, and review the change
by printing the table's rows with `--rows` on the base and on the head (PROCESS.md §8: a changed expected output
needs its reason in the journal and a verdict on old and new side by side).
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

ENGINE = Path(__file__).resolve().parents[1]
# The engine's source and its tests beside this script, not whatever the environment has installed: the corpus
# helpers live in the engine's tests (`tests.ledger.parity`), and the snapshot is of this tree's build.
sys.path[:0] = [str(ENGINE / "src"), str(ENGINE)]

from ledger_engine.ledger import fresh_load  # noqa: E402


def as_the_engine_runs() -> bool:
    """Whether this process hashes as the engine does: with the environment the engine gives a load it starts
    (`fresh_load.environment`, the same seed the sidecar gives the engine). `-I` (how `check_generated.py` runs
    generators) ignores `PYTHONHASHSEED`, and Beancount's `onecommodity`, `close_tree` and `commodity_attr` plugins
    word their errors and order their entries by set order, so the rows depend on the seed."""
    seed = fresh_load.environment()["PYTHONHASHSEED"]
    return os.environ.get("PYTHONHASHSEED") == seed and not sys.flags.ignore_environment


if __name__ == "__main__" and not as_the_engine_runs():
    again = [sys.executable, "-s", "-P", __file__, *sys.argv[1:]]  # this interpreter, this script, its arguments
    sys.exit(subprocess.run(again, env=fresh_load.environment(), check=False).returncode)  # noqa: S603

from tests.mirror import checksums  # noqa: E402

HEADER = (
    "GENERATED by engine/scripts/gen_mirror_checksums.py; do not edit (INV-19). The mirror's rows over every corpus "
    "root, per table: row count and SHA-256 of the normalized, sorted rows (BL-0057, S0096). A change detector: "
    "review a changed table with --rows on the base and the head."
)


def main() -> int:
    ap = argparse.ArgumentParser()
    group = ap.add_mutually_exclusive_group(required=True)
    group.add_argument("--stdout", action="store_true", help="print the snapshot")
    group.add_argument("--rows", nargs=2, metavar=("CASE", "TABLE"), help="print one table's normalized rows")
    args = ap.parse_args()
    with tempfile.TemporaryDirectory() as tmp:
        if args.rows:
            case, table = args.rows
            for name, rows in checksums.iter_rows(Path(tmp).resolve(), case):
                if name == table:
                    for row in rows:
                        sys.stdout.write(json.dumps(row, ensure_ascii=False) + "\n")
                    return 0
            sys.stderr.write(f"{case} has no table {table}\n")
            return 1
        built = checksums.build_all(Path(tmp).resolve())
    sys.stdout.write(checksums.render(HEADER, checksums.snapshot(built)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
