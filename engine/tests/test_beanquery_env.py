"""beanquery is in the engine's environment (ADR-0054 decision 1; owner decision 2026-10-26, S0037; BL-0081).

No BQL operation exists yet (CAP-ENGINE-BQL, M7). This proves only that the locked beanquery and its parser
library TatSu-LTS load and run together in this environment: beanquery's parser is generated by TatSu, so a
statement that runs end to end exercises both.

The probe runs in a child interpreter started like the engine (`python -I`) and reports JSON. beanquery and parts of
Beancount's API carry no type information, and EP-22 keeps pyright strict with no local loosening; their typed
facade (local stubs under `engine/typings/`, the gateway `ledger_engine.ledger.beancount_port`) comes with the first
BQL slice (S0037 journal, Decisions).
"""

from __future__ import annotations

import json
import subprocess
import sys
import tomllib
from importlib.metadata import version
from pathlib import Path
from typing import Any

LOCK = Path(__file__).resolve().parents[1] / "uv.lock"

PROBE = '''
import json, sys
from beancount import loader
from beanquery import query
from beanquery.parser import ParseError

entries, errors, options = loader.load_string("""
2026-01-01 open Assets:Cash EUR
2026-01-01 open Expenses:Food EUR
2026-01-02 * "Lunch"
  Expenses:Food  10.00 EUR
  Assets:Cash
""")
columns, rows = query.run_query(entries, options, sys.argv[1])
try:
    query.run_query(entries, options, "SELEC account")
    refused = None
except ParseError as e:
    refused = type(e).__name__
print(json.dumps({"errors": len(errors), "columns": [c.name for c in columns],
                  "rows": [[str(v) for v in r] for r in rows], "refused": refused}))
'''


def locked(name: str) -> str:
    packages: list[dict[str, Any]] = tomllib.loads(LOCK.read_text(encoding="utf-8"))["package"]
    return next(str(p["version"]) for p in packages if p["name"] == name)


def probe(statement: str) -> dict[str, Any]:
    r = subprocess.run(  # noqa: S603 (fixed argv: this interpreter and a literal probe)
        [sys.executable, "-I", "-c", PROBE, statement], capture_output=True, text=True, check=False
    )
    assert r.returncode == 0, r.stderr
    return json.loads(r.stdout)


def test_beanquery_and_tatsu_are_installed_at_the_locked_versions() -> None:
    assert version("beanquery") == locked("beanquery") == "0.2.0"  # ARCHITECTURE.md §10
    assert version("tatsu-lts") == locked("tatsu-lts")


def test_a_bql_statement_runs_and_a_malformed_one_is_refused_by_the_parser() -> None:
    out = probe("SELECT account, sum(number) AS total GROUP BY account ORDER BY account")
    assert out == {
        "errors": 0,
        "columns": ["account", "total"],
        "rows": [["Assets:Cash", "-10.00"], ["Expenses:Food", "10.00"]],
        "refused": "ParseError",
    }
