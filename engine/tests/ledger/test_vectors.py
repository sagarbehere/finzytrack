"""The engine passes the Beancount domain vectors (INV-02; BL-0002; ADR-0024; spec design/specs/kernel/vectors.md).

Each vector in `corpora/vectors/vectors.json` is an input and what Beancount 3.2.0 says about it, generated by
`scripts/oracle/gen_domain_vectors.py` and kept honest by `scripts/oracle/tests/test_domain_vectors.py`. Here the
engine's own path must say the same: the vector's ledger is loaded by `overlay.load` (once from disk, once as a
candidate in the overlay), and the outputs the spec gives the engine come from `grammar` and `beancount_port`, never
from Beancount called directly. Numbers are compared as Beancount's exact text (written scale included).

The `price` family is the main sidecar's (`PriceIndex`, L3-12) and the frontend tolerance port's outputs
(`needs_booking`, `port`) are the frontend's (L3-09); both pass the vectors when they are built.
"""

from __future__ import annotations

import json
from collections.abc import Callable
from decimal import Decimal
from pathlib import Path
from typing import Any

import pytest

from ledger_engine.ledger import beancount_port as port
from ledger_engine.ledger import grammar
from ledger_engine.ledger.overlay import Loaded, load
from ledger_engine.ledger.policy import DESKTOP

pytestmark = pytest.mark.inv("INV-02")

VECTORS = Path(__file__).resolve().parents[3] / "corpora" / "vectors" / "vectors.json"
DATA: dict[str, Any] = json.loads(VECTORS.read_text(encoding="utf-8"))
FAMILIES: dict[str, list[dict[str, Any]]] = DATA["families"]
ENGINE_FAMILIES = ("tolerance", "balance", "account", "currency", "precision", "booking")
NOT_THE_ENGINES = ("price",)  # the main sidecar's PriceIndex (L3-12)
NARRATION = "vector"  # the generator's marker for the transaction under test
ASSERTION_DATE = "2020-06-01"  # the generator's date for the item under test
VIAS = ("disk", "overlay")


def num(value: Decimal | None) -> str | None:
    return None if value is None else format(value, "f")


def messages(errors: list[port.BeancountError]) -> list[str]:
    return [str(e.message).splitlines()[0].strip() for e in errors]


def option_lines(options: list[list[str]]) -> str:
    return "".join(f'option "{k}" "{v}"\n' for k, v in options)


def load_text(tmp_path: Path, text: str, via: str) -> Loaded:
    root = tmp_path / "main.beancount"
    if via == "disk":
        root.write_bytes(text.encode("utf-8"))
        result = load(str(root), {}, DESKTOP)
    else:
        result = load(str(root), {str(root): text.encode("utf-8")}, DESKTOP)
    assert isinstance(result, Loaded), result
    return result


def the_transaction(loaded: Loaded) -> port.Transaction | None:
    found = [e for e in loaded.entries if isinstance(e, port.Transaction) and e.narration == NARRATION]
    assert len(found) <= 1
    return found[0] if found else None


def booked(p: port.Posting) -> dict[str, Any]:
    cost = None
    if p.cost is not None:
        c = p.cost
        assert isinstance(c, port.Cost), c
        cost = {
            "number": num(c.number),
            "currency": c.currency,
            "date": c.date.isoformat(),
            "label": c.label,
        }
    price = None if p.price is None else {"number": num(p.price.number), "currency": p.price.currency}
    units = None if p.units is None else {"number": num(p.units.number), "currency": p.units.currency}
    return {"account": p.account, "units": units, "cost": cost, "price": price, "interpolated": port.is_interpolated(p)}


def test_every_family_is_classed_and_none_is_empty() -> None:
    assert set(FAMILIES) == set(ENGINE_FAMILIES) | set(NOT_THE_ENGINES)
    assert all(FAMILIES[f] for f in ENGINE_FAMILIES)
    assert DATA["beancount"] == port.BEANCOUNT_VERSION


def check_tolerance(vector: dict[str, Any], via: str, tmp_path: Path) -> None:
    out = vector["output"]
    loaded = load_text(tmp_path, vector["input"]["ledger"], via)
    assert messages(loaded.errors) == out["errors"]
    txn = the_transaction(loaded)
    assert (txn is None) == out["dropped"]
    if txn is None:
        assert out["tolerances"] is None
        return
    check = grammar.transaction_balance(txn, loaded.options)
    assert {k: num(v) for k, v in check.tolerances.items()} == out["tolerances"]["by_currency"]
    assert num(check.default) == out["tolerances"]["default"]
    assert {k: num(v) for k, v in check.residual.items()} == out["residual"]
    assert check.balanced == out["balanced"]
    assert [booked(p) for p in txn.postings if port.is_interpolated(p)] == out["interpolated"]


def check_booking(vector: dict[str, Any], via: str, tmp_path: Path) -> None:
    out = vector["output"]
    loaded = load_text(tmp_path, vector["input"]["ledger"], via)
    assert messages(loaded.errors) == out["errors"]
    txn = the_transaction(loaded)
    assert (None if txn is None else [booked(p) for p in txn.postings]) == out["booked"]


def check_balance(vector: dict[str, Any], via: str, tmp_path: Path) -> None:
    inp, out = vector["input"], vector["output"]
    loaded = load_text(tmp_path, inp["ledger"], via)
    assert messages(loaded.errors) == out["errors"]
    found = [
        e
        for e in loaded.entries
        if isinstance(e, port.Balance) and e.account == inp["account"] and e.date.isoformat() == ASSERTION_DATE
    ]
    assert len(found) == 1
    check = grammar.balance_assertion(loaded.entries, found[0], loaded.options)
    assert num(check.tolerance) == out["tolerance"]
    assert num(check.actual) == out["actual"]
    assert num(check.difference) == out["difference"]


def check_account(vector: dict[str, Any], via: str, tmp_path: Path) -> None:
    loaded = load_text(tmp_path, option_lines(vector["input"]["options"]), via)
    roots = grammar.account_roots(loaded.options)
    for item in vector["items"]:
        name, out = item["input"]["name"], item["output"]
        result = grammar.parse_account(name, roots)
        assert (not isinstance(result, grammar.Invalid)) == out["valid"], name
        # A refused root option is the ledger's error, reported once by its load; the probe reports the name's own.
        if isinstance(result, grammar.Invalid):
            assert messages(loaded.errors) + list(result.errors) == out["errors"], name
        else:
            assert messages(loaded.errors) == out["errors"] == [], name
            assert result == name


def check_currency(vector: dict[str, Any], via: str, tmp_path: Path) -> None:
    del via, tmp_path  # the grammar probes parse text; nothing is loaded
    for item in vector["items"]:
        code, out = item["input"]["code"], item["output"]
        result = grammar.parse_currency(code)
        assert (not isinstance(result, grammar.Invalid)) == out["valid"], code
        if isinstance(result, grammar.Invalid):
            assert list(result.errors) == out["commodity_errors"] + out["price_base_errors"], code
        else:
            assert result == code


def check_precision(vector: dict[str, Any], via: str, tmp_path: Path) -> None:
    loaded = load_text(tmp_path, vector["input"]["ledger"], via)
    for item in vector["items"]:
        currency, out = item["input"]["currency"], item["output"]
        found = port.display_precision(loaded.options, currency)
        got = None if found is None else {"most_common": found.most_common, "maximum": found.maximum}
        want = None if out == {"most_common": None, "maximum": None} else out
        assert got == want, currency


# ---- one test per family: every vector, each way; a failure names the vector (no parametrize, so no test can be
# switched off by an empty list, scripts/check_invariants.py) ----------------------------------------------------

type Check = Callable[[dict[str, Any], str, Path], None]
CHECKS: dict[str, tuple[Check, tuple[str, ...]]] = {
    "tolerance": (check_tolerance, VIAS),
    "balance": (check_balance, VIAS),
    "account": (check_account, VIAS),
    "currency": (check_currency, ("parse",)),
    "precision": (check_precision, VIAS),
    "booking": (check_booking, VIAS),
}


def run_family(family: str, tmp_path_factory: pytest.TempPathFactory) -> None:
    check, vias = CHECKS[family]
    failures: list[str] = []
    ran = 0
    for vector in FAMILIES[family]:
        for via in vias:
            ran += 1
            try:
                check(vector, via, tmp_path_factory.mktemp("vector"))
            except AssertionError as e:
                failures.append(f"{vector['id']}@{via}: {e}")
    assert failures == []
    assert ran == len(FAMILIES[family]) * len(vias) > 0


def test_every_engine_family_has_a_check() -> None:
    assert set(CHECKS) == set(ENGINE_FAMILIES)


def test_the_tolerance_vectors(tmp_path_factory: pytest.TempPathFactory) -> None:
    run_family("tolerance", tmp_path_factory)


def test_the_balance_vectors(tmp_path_factory: pytest.TempPathFactory) -> None:
    run_family("balance", tmp_path_factory)


def test_the_account_vectors(tmp_path_factory: pytest.TempPathFactory) -> None:
    run_family("account", tmp_path_factory)


def test_the_currency_vectors(tmp_path_factory: pytest.TempPathFactory) -> None:
    run_family("currency", tmp_path_factory)


def test_the_precision_vectors(tmp_path_factory: pytest.TempPathFactory) -> None:
    run_family("precision", tmp_path_factory)


def test_the_booking_vectors(tmp_path_factory: pytest.TempPathFactory) -> None:
    run_family("booking", tmp_path_factory)
