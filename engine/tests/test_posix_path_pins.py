"""On macOS and Linux every path, journal record and protocol message is byte for byte as before the Windows path
model (S0127, BL-0279; INV-22: no write path changes behaviour on macOS or Linux).

`tests/fixtures/posix_path_pins.json` was written once on the slice's base commit (2e5b312f) by `observed()` below,
before any product change, and is never regenerated by hand: a difference here is a change to what macOS or Linux
split, name, fold, record or send, which the slice's rule forbids. The pin covers the path functions every write goes
through (`split_absolute`, `check_name`, `canonical_path`, `path_key`, the handles' `join`), the journal's encoding of
the record test's records and its refusals, the copy layout's places and rewrites, and the protocol's validation and
encoding of messages that carry paths. Runs on every OS but Windows, whose model is another (`tests/fs/
test_pathmodel.py`)."""

