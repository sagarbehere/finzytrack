def _outcome(f: Any, *args: object) -> object:
    try:
        return f(*args)
    except ValueError as e:
        return f"{type(e).__name__}: {e}"


def _records() -> dict[str, journal.Record]:
    one = RECORD.files[0]
    return {
        "record": RECORD,
        "one_file": refit(replace(RECORD, files=(one,), created_dirs=())),
        "root_level": refit(
            replace(
                RECORD,
                files=(journal.FileEntry("/a.bean", "/a.bean", "1" * 64, "2" * 64, "0-a.bean", one.temp),),
                created_dirs=(),
            )
        ),
        "windows_paths": replace(
            RECORD,
            files=(replace(one, canonical_path="C:\\w\\a.bean", path_key="C:\\W\\A.BEAN"),),
            created_dirs=(),
        ),
        "reserved_name": refit(
            replace(
                RECORD,
                files=(
                    journal.FileEntry(
                        "/w/L/aux.bean",
                        "/w/l/aux.bean",
                        "1" * 64,
                        "2" * 64,
                        "0-aux.bean",
                        journal.temp_name("aux.bean", RECORD.name),
                    ),
                ),
                created_dirs=(),
            )
        ),
    }


def _journal() -> dict[str, object]:
    out: dict[str, object] = {}
    for name, r in _records().items():
        try:
            data = journal.encode(r)
        except ValueError as e:
            out[name] = f"{type(e).__name__}: {e}"
            continue
        back = journal.decode(data)
        out[name] = {
            "bytes": data.decode(),
            "decodes": back == r,
            "needed_folders": journal.needed_folders(r.files, r.created_dirs),
        }
    raw = journal.encode(RECORD).decode()
    for name, old, new in (
        ("windows_canonical", "/w/L/inc/a.bean", "C:\\w\\L\\inc\\a.bean"),
        ("windows_key", "/w/l/inc/a.bean", "C:\\W\\L\\INC\\A.BEAN"),
        ("reserved_folder", "/w/L/inc", "/w/L/con"),
    ):
        out[f"decode_{name}"] = repr(journal.decode(raw.replace(old, json.dumps(new)[1:-1]).encode()))
    return out


def _copy_layout() -> dict[str, object]:
    b = "/data/ledgers"
    root = f"{b}/main.beancount"
    src = cl.SourceSet(
        root,
        (root, f"{b}/p/p.beancount", "/data/shared/a/r.beancount", "/data/shared/b/m.beancount"),
        (f"{b}/gone.beancount",),
        ("/data/shared/*/x*.beancount", f"{b}/y/*.beancount"),
        ("/data/documents/books", "/other/docs"),
        ("/data/documents/books/A/x.pdf", "/elsewhere/z.pdf"),
        (f"{b}/p",),
    )
    lay = cl.layout(src)
    data = (
        b'include "/data/shared/a/r.beancount"\n'
        b'include "../shared/b/m.beancount"\n'
        b'include "p/p.beancount"\n'
        b'option "documents" "../documents/books"\n'
        b'2020-01-01 document Assets:A "/elsewhere/z.pdf"\n'
    )
    parsed = cl.Parsed(
        ("/data/shared/a/r.beancount", "../shared/b/m.beancount", "p/p.beancount"),
        ("../documents/books",),
        ((5, "/elsewhere/z.pdf"),),
    )
    out = cl.rewrite(lay, root, data, parsed)
    pattern, table = cl.back(lay, "/new/copy")
    return {
        "layout": [lay.base, [list(mv) for mv in lay.moves]],
        "places": {p: cl.place(lay, p) for p in (*src.files, *src.document_files, "/nowhere/q")},
        "rewrite": None
        if out is None
        else repr(out)
        if not isinstance(out, cl.Rewritten)
        else [out.data.decode(), [list(q) for q in out.quoted]],
        "back": [pattern.pattern, table],
        "norm_path": {p: cl.norm_path(p) for p in ("//a/b", "/a/./b/../c", "///x")},
        "literal_folder": {g: cl.literal_folder(g) for g in ("/a/b/*.x", "/a/*/c", "/*", "/a/b.x")},
    }


def _protocol() -> dict[str, object]:
    out: dict[str, object] = {}
    for p in ("/a/b", "C:\\x", "\\\\s\\sh\\x", "a", ""):
        try:
            jf = m.JournalFile.model_validate({"path": p, "path_key": p, "created": False})
            out[f"journal_file {p!r}"] = jf.model_dump_json()
        except ValidationError as e:
            out[f"journal_file {p!r}"] = [err["type"] for err in e.errors()]
    change = m.SaveChange.model_validate({"path": "/w/L/Caf\u00e9.bean", "pre": None, "post": "x\n"})
    out["save_change"] = change.model_dump_json()
    for name in ("a", "a/b", "a\\b", "con"):
        try:
            out[f"component {name!r}"] = m.SaveConfine.model_validate(
                {"path": "/w", "volume": "6d3f0a52-8b1c-4e7a-9f20-3c5b7d9e1a40", "fs_type": name, "born": 1}
            ).model_dump_json()
        except ValidationError as e:
            out[f"component {name!r}"] = [err["type"] for err in e.errors()]
    return out


def observed() -> dict[str, object]:
    """What this build gives for every pinned input."""
    return {
        "split_absolute": {p: _outcome(split_absolute, p) for p in PATHS},
        "check_name": {n: _outcome(check_name, n) for n in NAMES},
        "paths": [[_outcome(core_paths.canonical_path, r), _outcome(core_paths.path_key, r)] for r in RESOLVED],
        "join": [join(a, b) for a, b in (("/", "a"), ("/a", "b"), ("/a", "b/c"))],
        "journal": _journal(),
        "copy_layout": _copy_layout(),
        "protocol": _protocol(),
    }


def _normal(value: object) -> object:
    """JSON's view of a value (tuples become lists), so the comparison is the file's."""
    return json.loads(json.dumps(value, ensure_ascii=False))


def test_posix_paths_the_journal_and_the_protocol_are_byte_for_byte_as_on_the_base_commit() -> None:
    """@regression-guard (it holds on the base 2e5b312f, where the pins were written; it fails if a POSIX output
    changes)."""
    pinned = json.loads(PINS.read_text(encoding="utf-8"))
    assert _normal(observed()) == pinned


if __name__ == "__main__":  # the one-time writer, run on the base commit only (see the module's docstring)
    PINS.parent.mkdir(exist_ok=True)
    PINS.write_text(json.dumps(_normal(observed()), ensure_ascii=False, indent=1, sort_keys=True) + "\n", "utf-8")
