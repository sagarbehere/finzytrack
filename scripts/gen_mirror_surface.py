#!/usr/bin/env python3
"""Generate design/specs/mirror/surface.md (the mirror surface reference) from its TOML source.

Usage: python3 scripts/gen_mirror_surface.py            # write the markdown
       python3 scripts/gen_mirror_surface.py --stdout   # print it (used by check_generated.py)
"""

from __future__ import annotations

import sys
import tomllib
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "design/specs/mirror/surface.toml"
TARGET = ROOT / "design/specs/mirror/surface.md"
HEADER = "<!-- GENERATED by scripts/gen_mirror_surface.py from design/specs/mirror/surface.toml. Do not edit. -->"


def cell(value: object) -> str:
    if isinstance(value, bool):
        text = "yes" if value else "no"
    elif isinstance(value, list):
        text = ", ".join(str(v) for v in value) if value else "—"
    else:
        text = str(value) if value else "—"
    return text.replace("|", "\\|").replace("\n", " ")


def change(c: dict) -> str:
    if c["change"] != "changed":
        return c["change"]
    return f"changed ({cell(c['cites'])}): {c['why']}"


def render(spec: dict) -> str:
    tables = spec["table"]
    v022 = spec["legacy"]["v0.2.2"]["tables"]
    cols = [c for t in tables for c in t["column"]]
    out = [HEADER, "", "# Mirror surface", ""]
    out.append("Every table and column of the v0.4 mirror at M1a, the `r_*` views and the v0.2.2 compatibility names. "
               "Conventions and rules: [README.md](README.md). Edit `surface.toml`, then run "
               "`python3 scripts/gen_mirror_surface.py`.")
    out.append("")
    origins = Counter(c["origin"] for c in cols)
    statuses = Counter(c["status"].split(":")[0] for c in cols)
    changes = Counter(c["change"] for c in cols)
    out.append(f"Surface version {spec['surface_version']}. {len(tables)} tables, {len(cols)} columns: "
               + ", ".join(f"{n} from {o}" for o, n in sorted(origins.items())) + "; "
               + ", ".join(f"{n} {k}" for k, n in sorted(changes.items())) + "; "
               + ", ".join(f"{n} {k}" for k, n in sorted(statuses.items())) + ".")
    out.append("")
    out.append("## Tables")
    out.append("")
    out.append("| Name | Base table | Public view | v0.2.2 name kept | As of | Status |")
    out.append("|---|---|---|---|---|---|")
    for t in tables:
        public = f"`r_{t['name']}`" if any(c["user_sql"] for c in t["column"]) else "— (internal)"
        out.append(f"| `{t['name']}` | `{t['base']}` | {public} | {'yes' if t['name'] in v022 else 'no'} | "
                   f"{cell(t['as_of'])} | {cell(t['status'])} |")
    for t in tables:
        out.append("")
        out.append(f"## `{t['name']}`")
        out.append("")
        out.append(f"- **One row is:** {t['row']}")
        out.append(f"- **As of:** {t['as_of']}")
        out.append(f"- **Origin:** {t['origin']}; **status:** {t['status']}; **cites:** {cell(t['cites'])}")
        if t["note"]:
            out.append(f"- **Note:** {t['note']}")
        out.append("")
        out.append("| Column | Type / format | Meaning | Source | Sign | Origin | Change from legacy | User SQL | Status |")
        out.append("|---|---|---|---|---|---|---|---|---|")
        for c in t["column"]:
            out.append(f"| `{c['name']}` | {c['type']} / {c['format']} | {cell(c['meaning'])} | {cell(c['source'])} | "
                       f"{cell(c['sign'])} | {c['origin']} | {cell(change(c))} | {cell(c['user_sql'])} | "
                       f"{cell(c['status'])} |")
    out.append("")
    out.append("## Compatibility names (ADR-0048)")
    out.append("")
    out.append("Each v0.2.2 table name is a view with exactly its v0.2.2 columns, in v0.2.2 order, served from the "
               "public view (or from the base table when the table has no public view). They keep working through "
               "0.4.x and are dropped later with a warning.")
    out.append("")
    out.append("| v0.2.2 name | Served from | Columns |")
    out.append("|---|---|---|")
    by_name = {t["name"]: t for t in tables}
    for name, legacy_cols in v022.items():
        t = by_name[name]
        src = f"`r_{name}`" if any(c["user_sql"] for c in t["column"]) else f"`{t['base']}`"
        out.append(f"| `{name}` | {src} | {', '.join(f'`{c}`' for c in legacy_cols)} |")
    out.append("")
    out.append("### Compute functions")
    out.append("")
    for f in spec["compat_function"]:
        out.append(f"- **`{f['name']}`** ({f['status']}, {f['milestone']}; {cell(f['cites'])}): served by {f['served_by']} "
                   f"Deprecation message: \"{f['message']}\" {f['located']}")
    out.append("")
    out.append("## Dropped (v0.3.0 only)")
    out.append("")
    for d in spec["dropped"]:
        out.append(f"- **`{d['item']}`** ({d['origin']}; {cell(d['cites'])}): {d['reason']}")
    return "\n".join(out) + "\n"


def main() -> int:
    with SOURCE.open("rb") as f:
        text = render(tomllib.load(f))
    if "--stdout" in sys.argv:
        sys.stdout.write(text)
    else:
        TARGET.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
