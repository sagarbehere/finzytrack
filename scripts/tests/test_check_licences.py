class Allowlist(unittest.TestCase):
    ALLOWED = {"MIT", "BSD-3-Clause"}
    PENDING = {"Apache-2.0"}

    def run_one(self, lic: str) -> tuple[list[str], list[str], str]:
        return cl.evaluate({"Python": [("pkg", "1.0", lic)]}, self.ALLOWED, self.PENDING)

    def test_allowed_licence_passes_and_is_listed(self) -> None:
        problems, warnings, text = self.run_one("MIT")
        self.assertEqual((problems, warnings), ([], []))
        self.assertIn("pkg 1.0  MIT", text)

    def test_licence_not_on_the_list_is_a_problem(self) -> None:
        problems, _, _ = self.run_one("GPL-3.0-only")
        self.assertEqual(len(problems), 1)

    def test_classifier_name_is_not_an_spdx_match(self) -> None:
        # Must not pass: "BSD License" does not say which BSD; it is not "BSD-3-Clause".
        problems, _, _ = self.run_one("BSD License")
        self.assertEqual(len(problems), 1)

    def test_one_allowed_option_of_an_or_passes(self) -> None:
        problems, _, _ = self.run_one("Apache-2.0 OR BSD-3-Clause")
        self.assertEqual(problems, [])

    def test_and_with_one_disallowed_part_is_a_problem(self) -> None:
        problems, _, _ = self.run_one("MIT AND GPL-3.0-only")
        self.assertEqual(len(problems), 1)

    def test_and_whose_parts_are_all_allowed_passes(self) -> None:
        # Verifier S0006 F2: the old split refused every AND.
        problems, _, _ = self.run_one("MIT AND BSD-3-Clause")
        self.assertEqual(problems, [])

    def test_parenthesised_or_inside_an_and_still_needs_the_and(self) -> None:
        # Verifier S0006 F2: stripping parentheses let "(MIT OR Apache-2.0) AND GPL-3.0-only" pass.
        problems, _, _ = self.run_one("(MIT OR Apache-2.0) AND GPL-3.0-only")
        self.assertEqual(len(problems), 1)

    def test_and_binds_tighter_than_or(self) -> None:
        # "GPL-3.0-only OR MIT AND BSD-3-Clause" means GPL-3.0-only OR (MIT AND BSD-3-Clause): allowed.
        problems, _, _ = self.run_one("GPL-3.0-only OR MIT AND BSD-3-Clause")
        self.assertEqual(problems, [])

    def test_and_with_a_pending_part_warns(self) -> None:
        problems, warnings, _ = self.run_one("MIT AND Apache-2.0")
        self.assertEqual((problems, len(warnings)), ([], 1))

    def test_with_exception_is_one_licence(self) -> None:
        problems, _, _ = cl.evaluate({"P": [("pkg", "1", "Apache-2.0 WITH LLVM-exception")]},
                                     {"Apache-2.0 WITH LLVM-exception"}, set())
        self.assertEqual(problems, [])
        problems, _, _ = self.run_one("Apache-2.0 WITH LLVM-exception")  # not listed as such: refused
        self.assertEqual(len(problems), 1)

    def test_malformed_expressions_are_problems(self) -> None:
        for bad in ("(MIT", "MIT)", "MIT OR", "AND MIT", "", "MIT WITH"):
            with self.subTest(expression=bad):
                problems, _, _ = self.run_one(bad)
                self.assertEqual(len(problems), 1)

    def test_pending_licence_warns_and_does_not_fail(self) -> None:
        problems, warnings, _ = self.run_one("Apache-2.0")
        self.assertEqual(problems, [])
        self.assertEqual(len(warnings), 1)

    def test_package_with_no_bundled_dependencies_says_so(self) -> None:
        problems, _, text = cl.evaluate({"Python": []}, self.ALLOWED, self.PENDING)
        self.assertEqual(problems, [])
        self.assertIn("== Python ==\n(no bundled dependencies)\n", text)

    def test_absent_package_is_noted(self) -> None:
        _, _, text = cl.evaluate({"JavaScript": None}, self.ALLOWED, self.PENDING)
        self.assertIn("(package not present yet)", text)


class EngineAllowlist(unittest.TestCase):
    """ADR-0054 decision 5: the engine (a GPL-2.0-only program) has its own list: GPL-2.0-compatible licences plus an
    explicit, reviewed list of Beancount's own dependencies, which pass with a warning pending legal advice. The
    main sidecar, the frontend and the shell keep the shared list (S0035 brief: "main: as today")."""

    ENGINE = cl.Policy(allowed=frozenset({"MIT", "BSD-3-Clause"}), pending=frozenset(),
                       reviewed={"regex": "Apache-2.0 AND CNRI-Python"})

    def run_engine(self, *deps: tuple[str, str, str]) -> tuple[list[str], list[str], str]:
        return cl.evaluate({"Python (ledger engine)": list(deps)}, {"MIT", "Apache-2.0"}, set(),
                           {"Python (ledger engine)": self.ENGINE})

    def test_a_licence_the_shared_list_allows_is_refused_in_the_engine(self) -> None:
        problems, _, _ = self.run_engine(("lib", "1", "Apache-2.0"))
        self.assertEqual(len(problems), 1)
        main_problems, _, _ = cl.evaluate({"Python (backend sidecar)": [("lib", "1", "Apache-2.0")]},
                                          {"MIT", "Apache-2.0"}, set(), {"Python (ledger engine)": self.ENGINE})
        self.assertEqual(main_problems, [])  # the override applies to its own group only

    def test_an_engine_licence_on_its_list_passes(self) -> None:
        self.assertEqual(self.run_engine(("lib", "1", "BSD-3-Clause"))[:2], ([], []))

    def test_a_reviewed_beancount_dependency_warns(self) -> None:
        problems, warnings, text = self.run_engine(("regex", "2026.9.29", "Apache-2.0 AND CNRI-Python"))
        self.assertEqual(problems, [])
        self.assertEqual(len(warnings), 1)
        self.assertIn("regex 2026.9.29  Apache-2.0 AND CNRI-Python", text)

    def test_a_reviewed_dependency_whose_licence_changed_is_refused(self) -> None:
        problems, _, _ = self.run_engine(("regex", "2027.1.1", "Apache-2.0 AND GPL-3.0-only"))
        self.assertEqual(len(problems), 1)

    def test_the_review_names_one_package_only(self) -> None:
        problems, _, _ = self.run_engine(("regex2", "1", "Apache-2.0 AND CNRI-Python"))
        self.assertEqual(len(problems), 1)

    def test_review_matches_normalized_names(self) -> None:
        policy = cl.Policy(allowed=frozenset(), pending=frozenset(), reviewed={"python-dateutil": "Apache-2.0"})
        problems, warnings, _ = cl.evaluate({"E": [("python_dateutil", "2.9.0.post0", "Apache-2.0")]}, set(), set(),
                                            {"E": policy})
        self.assertEqual((problems, len(warnings)), ([], 1))


