"""Meta-tests for the T1 licence check (ADR-0042, ADR-0054): only bundled packages count, and a bundled
package passes only with an allowed licence. Expected outcomes come from the check's rule text."""

from __future__ import annotations

import sys
import unittest
from pathlib import Path
from unittest import mock

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import check_licences as cl  # noqa: E402

EXPORT = """# This file was autogenerated by uv via the following command:
#    uv export --frozen --no-dev --no-emit-project --no-hashes
--index-url https://pypi.org/simple
fastapi==0.143.0
    # via finzytrack-backend
typing-extensions==4.16.0 ; python_full_version < '3.14'
pydantic[email]==2.14.0
"""


class RuntimeOnly(unittest.TestCase):
    def test_export_names_are_parsed_and_normalized(self) -> None:
        self.assertEqual(cl.runtime_names(EXPORT), {"fastapi", "typing-extensions", "pydantic"})

    def test_empty_export_means_nothing_is_bundled(self) -> None:
        self.assertEqual(cl.runtime_names("# header only\n"), set())

    def test_dev_tools_in_the_venv_are_not_bundled(self) -> None:
        installed = [("fastapi", "0.143.0", "MIT"), ("pytest", "9.1.1", "MIT"), ("coverage", "7.16.2", "Apache-2.0")]
        self.assertEqual(cl.bundled(installed, {"fastapi"}), [("fastapi", "0.143.0", "MIT")])

    def test_names_match_across_spelling(self) -> None:
        installed = [("typing_extensions", "4.16.0", "PSF-2.0")]
        self.assertEqual(cl.bundled(installed, {"typing-extensions"}), installed)

    def test_runtime_package_missing_from_the_venv_fails_closed(self) -> None:
        # Must not pass: a bundled package whose licence nobody read.
        with self.assertRaises(SystemExit):
            cl.bundled([("fastapi", "0.143.0", "MIT")], {"fastapi", "httpx"})


class Wiring(unittest.TestCase):
    """Verifier S0006 F8: python_deps reads the runtime closure (`--no-dev`) and filters the venv by it."""

    def test_python_deps_exports_without_dev_and_filters_the_venv(self) -> None:
        calls: list[list[str]] = []

        def fake_run(cmd, **_kwargs):
            calls.append(cmd)
            out = EXPORT if "export" in cmd else (
                '[{"Name": "fastapi", "Version": "0.143.0", "License": "MIT"},'
                ' {"Name": "pydantic", "Version": "2.14.0", "License": "MIT"},'
                ' {"Name": "typing_extensions", "Version": "4.16.0", "License": "PSF-2.0"},'
                ' {"Name": "pytest", "Version": "9.1.1", "License": "MIT"}]')
            return mock.Mock(stdout=out)

        with mock.patch.object(cl.subprocess, "run", fake_run), \
                mock.patch.object(cl.shutil, "which", lambda _n: "/bin/uv"), \
                mock.patch.object(cl.Path, "exists", lambda _p: True):
            deps = cl.python_deps()
        export = next(c for c in calls if "export" in c)
        self.assertIn("--no-dev", export)
        self.assertIn("--frozen", export)
        self.assertEqual(sorted(n for n, _, _ in deps or []), ["fastapi", "pydantic", "typing_extensions"])


class JavaScript(unittest.TestCase):
    REPORT = {
        "finzytrack-frontend@0.4.0-dev.0": {"licenses": "UNLICENSED"},
        "finzytrack-frontend-extra@1.0.0": {"licenses": "MIT"},
        "@vue/shared@3.5.43": {"licenses": "MIT"},
        "dual@1.0.0": {"licenses": ["MIT", "Apache-2.0"]},
    }

    def test_own_package_is_not_a_dependency(self) -> None:
        names = [n for n, _, _ in cl.js_from_report(self.REPORT, "finzytrack-frontend")]
        self.assertNotIn("finzytrack-frontend", names)

    def test_a_package_whose_name_only_starts_like_ours_is_kept(self) -> None:
        names = [n for n, _, _ in cl.js_from_report(self.REPORT, "finzytrack-frontend")]
        self.assertIn("finzytrack-frontend-extra", names)

    def test_scoped_names_and_licence_lists(self) -> None:
        deps = dict((n, (v, lic)) for n, v, lic in cl.js_from_report(self.REPORT, "finzytrack-frontend"))
        self.assertEqual(deps["@vue/shared"], ("3.5.43", "MIT"))
        self.assertEqual(deps["dual"], ("1.0.0", "MIT OR Apache-2.0"))


def metadata(edges: dict[str, list[tuple[str, list[str | None]]]], licences: dict[str, str | None]) -> dict:
    """A minimal `cargo metadata` document: package ids are "name version", edges carry dependency kinds."""
    return {
        "packages": [{"id": i, "name": i.split()[0], "version": i.split()[1], "license": lic}
                     for i, lic in licences.items()],
        "resolve": {"root": "shell 0.4.0", "nodes": [
            {"id": i, "deps": [{"pkg": d, "dep_kinds": [{"kind": k} for k in kinds]} for d, kinds in edges.get(i, [])]}
            for i in licences]},
    }


class Rust(unittest.TestCase):
    """ADR-0042: only what ships counts: crates reached from the shell through normal dependencies."""

    LICENCES = {
        "shell 0.4.0": "GPL-3.0-or-later",
        "tauri 2.12.3": "Apache-2.0 OR MIT",
        "serde 1.0.0": "MIT/Apache-2.0",
        "winapi 0.3.9": "MIT OR Apache-2.0",
        "cc 1.0.0": "MIT OR Apache-2.0",
        "proptest 1.0.0": "MIT OR Apache-2.0",
        "glob 0.3.0": "MIT OR Apache-2.0",
    }
    EDGES = {
        "shell 0.4.0": [("tauri 2.12.3", [None]), ("cc 1.0.0", ["build"]), ("proptest 1.0.0", ["dev"])],
        "tauri 2.12.3": [("serde 1.0.0", [None]), ("winapi 0.3.9", [None])],
        "cc 1.0.0": [("glob 0.3.0", [None])],
    }

    def names(self) -> list[str]:
        return [n for n, _, _ in cl.rust_from_metadata(metadata(self.EDGES, self.LICENCES))]

    def test_normal_dependencies_of_any_depth_ship(self) -> None:
        self.assertEqual(sorted(self.names()), ["serde", "tauri", "winapi"])

    def test_build_and_dev_dependencies_and_their_trees_do_not_ship(self) -> None:
        for name in ("cc", "proptest", "glob"):
            self.assertNotIn(name, self.names())

    def test_the_shell_itself_is_not_a_dependency(self) -> None:
        self.assertNotIn("shell", self.names())

    def test_an_edge_that_is_normal_on_some_target_ships(self) -> None:
        edges = {**self.EDGES, "shell 0.4.0": [("tauri 2.12.3", [None]), ("cc 1.0.0", ["build", None])]}
        names = [n for n, _, _ in cl.rust_from_metadata(metadata(edges, self.LICENCES))]
        self.assertIn("cc", names)
        self.assertIn("glob", names)

    def test_legacy_slash_means_or(self) -> None:
        deps = {n: lic for n, _, lic in cl.rust_from_metadata(metadata(self.EDGES, self.LICENCES))}
        self.assertEqual(deps["serde"], "MIT OR Apache-2.0")

    def test_missing_licence_field_is_unknown_and_refused(self) -> None:
        licences = {**self.LICENCES, "winapi 0.3.9": None}
        deps = {n: lic for n, _, lic in cl.rust_from_metadata(metadata(self.EDGES, licences))}
        self.assertEqual(deps["winapi"], "UNKNOWN")
        problems, _, _ = cl.evaluate({"Rust": [("winapi", "0.3.9", "UNKNOWN")]}, {"MIT"}, set())
        self.assertEqual(len(problems), 1)


class Allowlist(unittest.TestCase):
    ALLOWED = {"MIT", "BSD-3-Clause"}
    PENDING = {"Apache-2.0"}

    def run_one(self, lic: str) -> tuple[list[str], list[str], str]:
        return cl.evaluate({"Python": [("pkg", "1.0", lic)]}, self.ALLOWED, self.PENDING)

    def test_allowed_licence_passes_and_is_listed(self) -> None:
        problems, warnings, text = self.run_one("MIT")
        self.assertEqual((problems, warnings), ([], []))
        self.assertIn("pkg 1.0  MIT", text)

    def test_licence_not_on_the_list_is_a_problem(self) -> None:
        problems, _, _ = self.run_one("GPL-3.0-only")
        self.assertEqual(len(problems), 1)

    def test_classifier_name_is_not_an_spdx_match(self) -> None:
        # Must not pass: "BSD License" does not say which BSD; it is not "BSD-3-Clause".
        problems, _, _ = self.run_one("BSD License")
        self.assertEqual(len(problems), 1)

    def test_one_allowed_option_of_an_or_passes(self) -> None:
        problems, _, _ = self.run_one("Apache-2.0 OR BSD-3-Clause")
        self.assertEqual(problems, [])

    def test_and_with_one_disallowed_part_is_a_problem(self) -> None:
        problems, _, _ = self.run_one("MIT AND GPL-3.0-only")
        self.assertEqual(len(problems), 1)

    def test_and_whose_parts_are_all_allowed_passes(self) -> None:
        # Verifier S0006 F2: the old split refused every AND.
        problems, _, _ = self.run_one("MIT AND BSD-3-Clause")
        self.assertEqual(problems, [])

    def test_parenthesised_or_inside_an_and_still_needs_the_and(self) -> None:
        # Verifier S0006 F2: stripping parentheses let "(MIT OR Apache-2.0) AND GPL-3.0-only" pass.
        problems, _, _ = self.run_one("(MIT OR Apache-2.0) AND GPL-3.0-only")
        self.assertEqual(len(problems), 1)

    def test_and_binds_tighter_than_or(self) -> None:
        # "GPL-3.0-only OR MIT AND BSD-3-Clause" means GPL-3.0-only OR (MIT AND BSD-3-Clause): allowed.
        problems, _, _ = self.run_one("GPL-3.0-only OR MIT AND BSD-3-Clause")
        self.assertEqual(problems, [])

    def test_and_with_a_pending_part_warns(self) -> None:
        problems, warnings, _ = self.run_one("MIT AND Apache-2.0")
        self.assertEqual((problems, len(warnings)), ([], 1))

    def test_with_exception_is_one_licence(self) -> None:
        problems, _, _ = cl.evaluate({"P": [("pkg", "1", "Apache-2.0 WITH LLVM-exception")]},
                                     {"Apache-2.0 WITH LLVM-exception"}, set())
        self.assertEqual(problems, [])
        problems, _, _ = self.run_one("Apache-2.0 WITH LLVM-exception")  # not listed as such: refused
        self.assertEqual(len(problems), 1)

    def test_malformed_expressions_are_problems(self) -> None:
        for bad in ("(MIT", "MIT)", "MIT OR", "AND MIT", "", "MIT WITH"):
            with self.subTest(expression=bad):
                problems, _, _ = self.run_one(bad)
                self.assertEqual(len(problems), 1)

    def test_pending_licence_warns_and_does_not_fail(self) -> None:
        problems, warnings, _ = self.run_one("Apache-2.0")
        self.assertEqual(problems, [])
        self.assertEqual(len(warnings), 1)

    def test_package_with_no_bundled_dependencies_says_so(self) -> None:
        problems, _, text = cl.evaluate({"Python": []}, self.ALLOWED, self.PENDING)
        self.assertEqual(problems, [])
        self.assertIn("== Python ==\n(no bundled dependencies)\n", text)

    def test_absent_package_is_noted(self) -> None:
        _, _, text = cl.evaluate({"JavaScript": None}, self.ALLOWED, self.PENDING)
        self.assertIn("(package not present yet)", text)


if __name__ == "__main__":
    unittest.main()
