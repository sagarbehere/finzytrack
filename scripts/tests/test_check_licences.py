class Wiring(unittest.TestCase):
    """Verifier S0006 F8: python_deps reads the runtime closure (`--no-dev`) and filters the venv by it."""

    def test_python_deps_exports_without_dev_and_filters_the_venv(self) -> None:
        calls: list[list[str]] = []

        def fake_run(cmd, **_kwargs):
            calls.append(cmd)
            out = EXPORT if "export" in cmd else (
                '[{"Name": "fastapi", "Version": "0.143.0", "License": "MIT"},'
                ' {"Name": "pydantic", "Version": "2.14.0", "License": "MIT"},'
                ' {"Name": "typing_extensions", "Version": "4.16.0", "License": "PSF-2.0"},'
                ' {"Name": "pytest", "Version": "9.1.1", "License": "MIT"}]')
            return mock.Mock(stdout=out)

        with mock.patch.object(cl.subprocess, "run", fake_run), \
                mock.patch.object(cl.shutil, "which", lambda _n: "/bin/uv"), \
                mock.patch.object(cl.Path, "exists", lambda _p: True):
            deps = cl.python_deps()
        export = next(c for c in calls if "export" in c)
        self.assertIn("--no-dev", export)
        self.assertIn("--frozen", export)
        self.assertEqual(sorted(n for n, _, _ in deps or []), ["fastapi", "pydantic", "typing_extensions"])


