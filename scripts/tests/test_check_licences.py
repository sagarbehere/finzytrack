"""Meta-tests for the T1 licence check (ADR-0042, ADR-0054): only bundled packages count, and a bundled
package passes only with an allowed licence. Expected outcomes come from the check's rule text."""

from __future__ import annotations

import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import check_licences as cl  # noqa: E402

EXPORT = """# This file was autogenerated by uv via the following command:
#    uv export --frozen --no-dev --no-emit-project --no-hashes
--index-url https://pypi.org/simple
-e ./vendored/pkg
fastapi==0.143.0
    # via finzytrack-backend
typing-extensions==4.16.0 ; python_full_version < '3.14'
pydantic[email]==2.14.0
"""


class RuntimeOnly(unittest.TestCase):
    def test_export_names_are_parsed_and_normalized(self) -> None:
        self.assertEqual(cl.runtime_names(EXPORT), {"fastapi", "typing-extensions", "pydantic"})

    def test_empty_export_means_nothing_is_bundled(self) -> None:
        self.assertEqual(cl.runtime_names("# header only\n"), set())

    def test_dev_tools_in_the_venv_are_not_bundled(self) -> None:
        installed = [("fastapi", "0.143.0", "MIT"), ("pytest", "9.1.1", "MIT"), ("coverage", "7.16.2", "Apache-2.0")]
        self.assertEqual(cl.bundled(installed, {"fastapi"}), [("fastapi", "0.143.0", "MIT")])

    def test_names_match_across_spelling(self) -> None:
        installed = [("typing_extensions", "4.16.0", "PSF-2.0")]
        self.assertEqual(cl.bundled(installed, {"typing-extensions"}), installed)

    def test_runtime_package_missing_from_the_venv_fails_closed(self) -> None:
        # Must not pass: a bundled package whose licence nobody read.
        with self.assertRaises(SystemExit):
            cl.bundled([("fastapi", "0.143.0", "MIT")], {"fastapi", "httpx"})


class Allowlist(unittest.TestCase):
    ALLOWED = {"MIT", "BSD-3-Clause"}
    PENDING = {"Apache-2.0"}

    def run_one(self, lic: str) -> tuple[list[str], list[str], str]:
        return cl.evaluate({"Python": [("pkg", "1.0", lic)]}, self.ALLOWED, self.PENDING)

    def test_allowed_licence_passes_and_is_listed(self) -> None:
        problems, warnings, text = self.run_one("MIT")
        self.assertEqual((problems, warnings), ([], []))
        self.assertIn("pkg 1.0  MIT", text)

    def test_licence_not_on_the_list_is_a_problem(self) -> None:
        problems, _, _ = self.run_one("GPL-3.0-only")
        self.assertEqual(len(problems), 1)

    def test_classifier_name_is_not_an_spdx_match(self) -> None:
        # Must not pass: "BSD License" does not say which BSD; it is not "BSD-3-Clause".
        problems, _, _ = self.run_one("BSD License")
        self.assertEqual(len(problems), 1)

    def test_one_allowed_option_of_an_or_passes(self) -> None:
        problems, _, _ = self.run_one("Apache-2.0 OR BSD-3-Clause")
        self.assertEqual(problems, [])

    def test_and_needs_every_part_so_it_does_not_pass_on_one(self) -> None:
        problems, _, _ = self.run_one("MIT AND GPL-3.0-only")
        self.assertEqual(len(problems), 1)

    def test_pending_licence_warns_and_does_not_fail(self) -> None:
        problems, warnings, _ = self.run_one("Apache-2.0")
        self.assertEqual(problems, [])
        self.assertEqual(len(warnings), 1)

    def test_package_with_no_bundled_dependencies_says_so(self) -> None:
        problems, _, text = cl.evaluate({"Python": []}, self.ALLOWED, self.PENDING)
        self.assertEqual(problems, [])
        self.assertIn("== Python ==\n(no bundled dependencies)\n", text)

    def test_absent_package_is_noted(self) -> None:
        _, _, text = cl.evaluate({"JavaScript": None}, self.ALLOWED, self.PENDING)
        self.assertIn("(package not present yet)", text)


if __name__ == "__main__":
    unittest.main()
