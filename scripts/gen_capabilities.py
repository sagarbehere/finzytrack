#!/usr/bin/env python3
"""Generate design/capabilities.md (the "did we do X?" index) from design/capabilities.toml.

Usage: python3 scripts/gen_capabilities.py            # write design/capabilities.md
       python3 scripts/gen_capabilities.py --stdout   # print it (used by check_generated.py)
"""

from __future__ import annotations

import sys
import tomllib
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "design/capabilities.toml"
TARGET = ROOT / "design/capabilities.md"
HEADER = "<!-- GENERATED by scripts/gen_capabilities.py from design/capabilities.toml. Do not edit. -->"


SHORT = 100  # characters in an index label


def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ") if text else "—"


def short(text: str) -> str:
    """The capability's label for the index: up to its first clause (`; ` or `. `), at most SHORT characters,
    cut on a word with an ellipsis."""
    depth, code = 0, False
    for i, ch in enumerate(text):
        if ch == "`":
            code = not code
        elif not code and ch == "(":
            depth += 1
        elif not code and ch == ")":
            depth = max(depth - 1, 0)
        elif not code and depth == 0 and text[i : i + 2] in ("; ", ". "):
            text = text[:i]
            break
    text = text.strip().rstrip(".")
    if len(text) > SHORT:
        text = text[:SHORT].rsplit(" ", 1)[0].rstrip(" ,;:") + "…"
    return cell(text)


def render(caps: list[dict]) -> str:
    out = [HEADER, "", "# Capability map", ""]
    out.append(
        "Every user-visible capability of Finzytrack, with its status: `planned`, `partial`, `built`, "
        "`cut` (absent on purpose) or `deferred` (not in v0.4.0). This page is the index; each row's full "
        "description, what changes in v0.4, where it lived in v0.3, its doc page, backlog items, ADRs, code and "
        "tests are in `design/capabilities.toml` (search for the ID). Edit the `.toml`, then run "
        "`python3 scripts/gen_capabilities.py`. Rules: `design/process/PROCESS.md` (\"Project memory\")."
    )
    out.append("")
    by_status = Counter(c["status"] for c in caps)
    blocking = sum(1 for c in caps if c["release_blocking"] == "yes")
    out.append(
        "**Totals:** " + ", ".join(f"{k} {by_status[k]}" for k in sorted(by_status))
        + f"; {len(caps)} rows; release-blocking {blocking}."
    )
    out.append("")
    areas: dict[str, list[dict]] = {}
    for c in caps:
        areas.setdefault(c["area"], []).append(c)
    for area, rows in areas.items():
        out += [f"## {area}", ""]
        out.append("| ID | Capability | v0.4 | Status | Milestone | Blocks release |")
        out.append("|---|---|---|---|---|---|")
        for c in rows:
            out.append(
                "| " + " | ".join([
                    c["id"], short(c["capability"]), c["v04"], c["status"],
                    c.get("milestone", "—"), c["release_blocking"],
                ]) + " |"
            )
        out.append("")
    return "\n".join(out)


def load() -> list[dict]:
    with SOURCE.open("rb") as fh:
        return tomllib.load(fh)["capability"]


def main(argv: list[str]) -> int:
    text = render(load())
    if "--stdout" in argv:
        sys.stdout.write(text)
    else:
        TARGET.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
