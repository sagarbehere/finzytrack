#!/usr/bin/env python3
"""Generate design/capabilities.md (the "did we do X?" index) from design/capabilities.toml.

Usage: python3 scripts/gen_capabilities.py            # write design/capabilities.md
       python3 scripts/gen_capabilities.py --stdout   # print it (used by check_generated.py)
"""

from __future__ import annotations

import sys
import tomllib
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "design/capabilities.toml"
TARGET = ROOT / "design/capabilities.md"
HEADER = "<!-- GENERATED by scripts/gen_capabilities.py from design/capabilities.toml. Do not edit. -->"


def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ") if text else "—"


def render(caps: list[dict]) -> str:
    out = [HEADER, "", "# Capability map", ""]
    out.append(
        "Every user-visible capability of Finzytrack, with its status: `planned`, `partial`, `built`, "
        "`cut` (absent on purpose) or `deferred` (not in v0.4.0). Edit `design/capabilities.toml`, then run "
        "`python3 scripts/gen_capabilities.py`. Rules: `design/process/PROCESS.md` (\"Project memory\")."
    )
    out.append("")
    by_status = Counter(c["status"] for c in caps)
    blocking = sum(1 for c in caps if c["release_blocking"] == "yes")
    out.append(
        "**Totals:** " + ", ".join(f"{k} {by_status[k]}" for k in sorted(by_status))
        + f"; {len(caps)} rows; release-blocking {blocking}."
    )
    out.append("")
    areas: dict[str, list[dict]] = {}
    for c in caps:
        areas.setdefault(c["area"], []).append(c)
    for area, rows in areas.items():
        out += [f"## {area}", ""]
        out.append("| ID | Capability | v0.4 | Status | Milestone | Blocks release | Doc | Backlog | ADRs | Tests |")
        out.append("|---|---|---|---|---|---|---|---|---|---|")
        for c in rows:
            v04 = f"**{c['v04']}**: {c['v04_note']}" if c.get("v04_note") else f"**{c['v04']}**"
            out.append(
                "| " + " | ".join([
                    c["id"],
                    cell(c["capability"]),
                    cell(v04),
                    c["status"],
                    c.get("milestone", "—"),
                    c["release_blocking"],
                    cell(c.get("doc", "")),
                    cell(", ".join(c.get("backlog", []))),
                    cell(", ".join(c.get("adrs", []))),
                    cell(", ".join(c.get("tests", []))),
                ]) + " |"
            )
        out.append("")
    return "\n".join(out)


def load() -> list[dict]:
    with SOURCE.open("rb") as fh:
        return tomllib.load(fh)["capability"]


def main(argv: list[str]) -> int:
    text = render(load())
    if "--stdout" in argv:
        sys.stdout.write(text)
    else:
        TARGET.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
