#!/usr/bin/env python3
"""T1 licence check (owner decision, review:F §2 item 9): bundled dependencies use allowed licences, and
THIRD_PARTY_NOTICES lists every one of them.

Sources, once each package exists: the backend venv (pip-licenses 5.5.5), frontend/node_modules
(license-checker-rseidelsohn 5.0.1) and shell/src-tauri (cargo-about 0.9.2 / cargo-deny 0.20.2). Only what is
bundled counts: for the backend, the runtime closure of its lockfile (`uv export --no-dev`), never the dev
tools installed beside it; a runtime package the venv does not report fails closed. A package that exists but
whose tool is missing fails closed. Licences listed under [pending_legal_advice] pass with a
warning until the owner's legal advice settles them.
Usage: python3 scripts/check_licences.py [--write-notices]
"""

from __future__ import annotations

import json
import re
import shutil
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NOTICES = ROOT / "THIRD_PARTY_NOTICES"
HEADER = "Third-party notices for Finzytrack. GENERATED by scripts/check_licences.py --write-notices. Do not edit.\n"


def norm(name: str) -> str:
    """PEP 503 name normalization, so `Typing_Extensions` and `typing-extensions` are one package."""
    return re.sub(r"[-_.]+", "-", name).lower()


def runtime_names(requirements: str) -> set[str]:
    """Package names in `uv export` requirements output (comments, markers and options ignored)."""
    names = set()
    for line in requirements.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line or line.startswith("-"):
            continue
        names.add(norm(re.split(r"[=<>!~;\[ ]", line, maxsplit=1)[0]))
    return names


def bundled(installed: list[tuple[str, str, str]], runtime: set[str]) -> list[tuple[str, str, str]]:
    """The installed packages that are bundled. A runtime package missing from the venv fails closed."""
    by_name = {norm(n): (n, v, lic) for n, v, lic in installed}
    missing = sorted(runtime - by_name.keys())
    if missing:
        raise SystemExit(f"check-licences: runtime packages not installed in backend/.venv: {', '.join(missing)}")
    return [by_name[n] for n in sorted(runtime)]


def python_deps() -> list[tuple[str, str, str]] | None:
    if not (ROOT / "backend/pyproject.toml").exists():
        return None
    tool = ROOT / "backend/.venv/bin/pip-licenses"
    if not tool.exists():
        raise SystemExit("check-licences: backend exists but backend/.venv/bin/pip-licenses is missing")
    uv = shutil.which("uv")
    if uv is None:
        raise SystemExit("check-licences: backend exists but uv is not on PATH")
    export = subprocess.run(
        [uv, "export", "--frozen", "--no-dev", "--no-emit-project", "--no-hashes", "--directory", str(ROOT / "backend")],
        capture_output=True, text=True, check=True,
    )
    out = subprocess.run([str(tool), "--format=json", "--with-system", "--from=mixed"], capture_output=True, text=True, check=True)
    installed = [(d["Name"], d["Version"], d["License"]) for d in json.loads(out.stdout)]
    return bundled(installed, runtime_names(export.stdout))


def js_deps() -> list[tuple[str, str, str]] | None:
    if not (ROOT / "frontend/package.json").exists():
        return None
    tool = ROOT / "frontend/node_modules/.bin/license-checker-rseidelsohn"
    if not tool.exists():
        raise SystemExit("check-licences: frontend exists but license-checker-rseidelsohn is missing")
    out = subprocess.run([str(tool), "--production", "--json"], cwd=ROOT / "frontend", capture_output=True, text=True, check=True)
    own = json.loads((ROOT / "frontend/package.json").read_text())["name"]
    return js_from_report(json.loads(out.stdout), own)


def js_from_report(report: dict[str, dict], own: str) -> list[tuple[str, str, str]]:
    """(name, version, licence) per package of a license-checker report, without the app's own package."""
    deps = []
    for key, info in report.items():
        name, _, version = key.rpartition("@")
        if name == own:
            continue
        lic = info.get("licenses", "UNKNOWN")
        deps.append((name, version, lic if isinstance(lic, str) else " OR ".join(lic)))
    return deps


REFUSED, PENDING, ALLOWED = 0, 1, 2


def judge(expression: str, allowed: set[str], pending: set[str]) -> int:
    """Judge an SPDX licence expression: `OR` takes its best part, `AND` its worst, `A WITH B` is one
    licence. Parentheses group. Anything that does not parse (or a classifier name such as "BSD License",
    which is not an SPDX id) is refused: the check fails closed."""
    tokens = expression.replace("(", " ( ").replace(")", " ) ").split()
    pos = 0

    def peek() -> str | None:
        return tokens[pos] if pos < len(tokens) else None

    def take() -> str:
        nonlocal pos
        pos += 1
        return tokens[pos - 1]

    def term() -> str:
        words = []
        while peek() not in (None, "AND", "OR", "WITH", "(", ")"):
            words.append(take())
        if not words:
            raise ValueError("licence term expected")
        return " ".join(words)

    def atom() -> int:
        if peek() == "(":
            take()
            value = disjunction()
            if peek() != ")":
                raise ValueError("unbalanced parentheses")
            take()
            return value
        name = term()
        if peek() == "WITH":
            take()
            name = f"{name} WITH {term()}"
        return ALLOWED if name in allowed else PENDING if name in pending else REFUSED

    def conjunction() -> int:
        value = atom()
        while peek() == "AND":
            take()
            value = min(value, atom())
        return value

    def disjunction() -> int:
        value = conjunction()
        while peek() == "OR":
            take()
            value = max(value, conjunction())
        return value

    try:
        value = disjunction()
    except ValueError:
        return REFUSED
    return value if pos == len(tokens) else REFUSED


def evaluate(
    groups: dict[str, list[tuple[str, str, str]] | None], allowed: set[str], pending: set[str]
) -> tuple[list[str], list[str], str]:
    """(problems, warnings, notices text), each dependency judged by `judge`."""
    problems, warnings, lines = [], [], [HEADER]
    for title, deps in groups.items():
        lines.append(f"\n== {title} ==\n")
        if deps is None:
            lines.append("(package not present yet)\n")
            continue
        if not deps:
            lines.append("(no bundled dependencies)\n")
        for name, version, lic in sorted(deps):
            verdict = judge(lic, allowed, pending)
            if verdict == ALLOWED:
                pass
            elif verdict == PENDING:
                warnings.append(f"{name} {version}: {lic} (pending legal advice)")
            else:
                problems.append(f"{name} {version}: licence {lic!r} is not on the allowlist")
            lines.append(f"{name} {version}  {lic}\n")
    return problems, warnings, "".join(lines)


def main(argv: list[str]) -> int:
    with (ROOT / "licences.allow.toml").open("rb") as fh:
        cfg = tomllib.load(fh)
    allowed, pending = set(cfg["allowed"]), set(cfg.get("pending_legal_advice", {}))
    groups = {"Python (backend sidecar)": python_deps(), "JavaScript (frontend)": js_deps()}
    if (ROOT / "shell/src-tauri/Cargo.toml").exists():
        print("check-licences: shell/ exists; wire cargo-about/cargo-deny here (backlog BL-0033)", file=sys.stderr)
        return 1
    problems, warnings, text = evaluate(groups, allowed, pending)
    if "--write-notices" in argv:
        NOTICES.write_text(text, encoding="utf-8")
    elif not NOTICES.exists() or NOTICES.read_text(encoding="utf-8") != text:
        problems.append("THIRD_PARTY_NOTICES is stale; run python3 scripts/check_licences.py --write-notices")
    for w in warnings:
        print(f"check-licences: warning: {w}", file=sys.stderr)
    for p in problems:
        print(f"check-licences: {p}", file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
