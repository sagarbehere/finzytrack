#!/usr/bin/env python3
"""T1 licence check (owner decision, review:F §2 item 9): bundled dependencies use allowed licences, and
THIRD_PARTY_NOTICES lists every one of them.

Sources, once each package exists: the backend and engine venvs (pip-licenses 5.5.5), frontend/node_modules
(license-checker-rseidelsohn 5.0.1) and shell/src-tauri (`cargo metadata`: the crates reached from the shell
through normal dependencies, on every target; cargo-about collects the licence texts at bundling). Only what is
bundled counts: for the backend, the runtime closure of its lockfile (`uv export --no-dev`), never the dev
tools installed beside it; a runtime package the venv does not report fails closed. A package that exists but
whose tool is missing fails closed. Licences listed under [pending_legal_advice] pass with a
warning until the owner's legal advice settles them.
Two lists (ADR-0054 decision 5): the ledger engine is a GPL-2.0-only program and is judged by `[engine]` (GPL-2.0-
compatible licences, plus the reviewed Beancount dependencies in `[engine.reviewed]`, each passing with a warning
only while its licence is the reviewed expression); everything else by the shared list. pip-licenses reports
trove-classifier names for some packages; `[mapping.<package>]` gives the reviewed SPDX id for one exact version
(BL-0050).
Acknowledgments (S0037): a licence may require every redistribution to keep an acknowledgment sentence (TatSu-LTS's
clause 4, the 4-clause BSD and Apache 1.1 clauses). For each Python process the check runs `read_texts` with that
venv's own interpreter, which reads every licence and notice file each installed distribution declares or records
(`read_texts` says which), and judges each bundled package with that process's own text and version. A text that
asks for "the following acknowledgment" needs an `[acknowledgment.<package>]` entry for that exact version whose text
equals the sentence the licence quotes, and the notices carry it under the package's line in that process's group.
Fails closed: a bundled package whose text was not read, a declared or recorded licence file that cannot be read, an
entry for a package that is not bundled or whose text cannot be confirmed, and a bundled package that ships no
licence text at all, unless `[no_licence_text.<package>]` records its exact version and why. Stated limits: the
check finds the clauses by their wording ("following acknowledg(e)ment"), so a licence that words the duty otherwise
is not caught; an unquoted sentence is read up to the first full stop that ends a line, unless the next line starts
in lower case, so a sentence wrapped right after an inner full stop ("Inc.") before a capital is cut short (the
entry's source says who read the licence); JavaScript and Rust licence texts are not read here (BL-0086).
Other platforms and options (BL-0050, S0105): a runtime package behind a platform marker that does not hold here
(`colorama ; sys_platform == 'win32'`; the marker evaluated by the venv's own interpreter) is bundled on another OS but
absent from this venv: it is judged from an `[other_platform.<package>]` entry for its exact pinned version (SPDX id,
where its licence was read, and the acknowledgment its licence requires, "" for none), and an entry no such package
uses is stale. Without an entry, with another version, or with a marker that holds here, it fails closed. An option
line of `uv export` other than `--index-url`/`--extra-index-url` (an editable or path dependency `-e <path>`, an
include) fails closed, since the package it brings would be bundled unchecked.
Usage: python3 scripts/check_licences.py [--write-notices]
(Internal: `--read-texts [path...]` prints `read_texts` as JSON, and `--eval-markers` reads a JSON list of markers on
stdin and prints whether each holds; the check runs both inside each Python venv.)
"""

