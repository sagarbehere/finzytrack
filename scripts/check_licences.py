def norm(name: str) -> str:
    """PEP 503 name normalization, so `Typing_Extensions` and `typing-extensions` are one package."""
    return re.sub(r"[-_.]+", "-", name).lower()


@dataclass(frozen=True)
class Requirement:
    """One line of `uv export`: the normalized name, its pinned version (None when not `==`), its marker or None."""

    name: str
    version: str | None
    marker: str | None


@dataclass(frozen=True)
class Elsewhere:
    """A package bundled on another OS only, reviewed for one exact version (BL-0050): its SPDX id, where its licence
    was read, and the acknowledgment its licence requires ("" for none)."""

    version: str
    spdx: str
    source: str
    acknowledgment: str


# Options of `uv export` that bring no package (S0105, BL-0050 F7): any other option line fails closed.
HARMLESS_OPTIONS = ("--index-url", "--extra-index-url")


def runtime_requirements(requirements: str) -> tuple[list[Requirement], list[str]]:
    """Every requirement line of `uv export` output, and the option lines that fail closed. A universal resolution
    may fork a package into one line per platform with different versions, so each line is kept and judged on its
    own (S0105 part B round 1, F2)."""
    reqs: list[Requirement] = []
    problems: list[str] = []
    for raw in requirements.splitlines():
        line = raw.split(" #", 1)[0].strip() if not raw.lstrip().startswith("#") else ""
        if not line:
            continue
        if line.startswith("-"):
            if line.split()[0].split("=", 1)[0] not in HARMLESS_OPTIONS:
                problems.append(f"uv export line {line!r}: an editable or path dependency or an include; the package "
                                "it brings would be bundled unchecked")
            continue
        spec, _, marker = line.partition(";")
        name = norm(re.split(r"[=<>!~\[ @]", spec.strip(), maxsplit=1)[0])
        pinned = re.search(r"==\s*([^\s,;]+)", spec)
        reqs.append(Requirement(name, pinned.group(1) if pinned else None, marker.strip() or None))
    return reqs, problems


def runtime_names(requirements: str) -> set[str]:
    """Package names in `uv export` requirements output (comments, markers and options ignored)."""
    return {r.name for r in runtime_requirements(requirements)[0]}


def bundled(
    installed: list[tuple[str, str, str]], runtime: set[str] | list[Requirement], project: str = "backend",
    elsewhere: dict[str, Elsewhere] | None = None, holds: dict[str, bool] | None = None, used: set[str] | None = None,
) -> list[tuple[str, str, str]]:
    """The bundled packages: for each requirement line, the installed package (of its pinned version), or, when its
    marker does not hold here, its reviewed `elsewhere` entry for its exact pinned version (named in `used`). Any other
    line fails closed, so a forked line of another version is never covered by its sibling."""
    by_name = {norm(n): (n, v, lic) for n, v, lic in installed}
    reqs = runtime if isinstance(runtime, list) else [Requirement(n, None, None) for n in sorted(runtime)]
    out: list[tuple[str, str, str]] = []
    missing: list[str] = []
    for req in reqs:
        name, entry = req.name, (elsewhere or {}).get(req.name)
        inst = by_name.get(name)
        if inst is not None and (req.version is None or inst[1] == req.version):
            out.append(inst)
        elif req.marker and (holds or {}).get(req.marker) is False and entry is not None \
                and req.version is not None and entry.version == req.version:
            out.append((name, req.version, entry.spdx))
            if used is not None:
                used.add(name)
        else:
            why = "" if not req.marker else f" (marker {req.marker!r}" + (
                ": it holds here)" if (holds or {}).get(req.marker) else
                ": bundled on another OS; add [other_platform] for its exact version)" if entry is None or
                entry.version != req.version else ": not evaluated)")
            missing.append(f"{name}{'==' + req.version if req.version else ''}{why}")
    if missing:
        raise SystemExit(f"check-licences: runtime packages not installed in {project}/.venv: {', '.join(missing)}")
    return sorted(dict.fromkeys(out), key=lambda d: (norm(d[0]), d[1]))


def evaluate_markers(project: str, markers: list[str]) -> dict[str, bool]:
    """Whether each marker holds for the venv's own interpreter (packaging's evaluation, run inside it)."""
    if not markers:
        return {}
    r = subprocess.run([str(ROOT / project / ".venv/bin/python"), "-I", str(Path(__file__).resolve()), "--eval-markers"],
                       input=json.dumps(markers), capture_output=True, text=True, check=False)
    if r.returncode != 0:
        raise SystemExit(f"check-licences: {project}: platform markers could not be evaluated: {r.stderr.strip()[-300:]}")
    return {k: v for k, v in json.loads(r.stdout).items() if isinstance(v, bool)}


def stale_elsewhere(entries: dict[str, Elsewhere], used: set[str]) -> list[str]:
    return [f"{name}: [other_platform] names a package no Python process bundles on another OS only; remove the entry"
            for name in sorted(entries.keys() - used)]


def python_deps(project: str = "backend", into: dict[str, str] | None = None,
                elsewhere: dict[str, Elsewhere] | None = None, used: set[str] | None = None,
                ) -> list[tuple[str, str, str]] | None:
    """The bundled packages of one Python process: `backend` (the main sidecar) or `engine` (ADR-0054). With `into`,
    each bundled package's licence and notice texts are added to it (normalized name -> text); `elsewhere` and `used`
    as in `bundled`."""
    if not (ROOT / project / "pyproject.toml").exists():
        return None
    tool = ROOT / project / ".venv/bin/pip-licenses"
    if not tool.exists():
        raise SystemExit(f"check-licences: {project} exists but {project}/.venv/bin/pip-licenses is missing")
    uv = shutil.which("uv")
    if uv is None:
        raise SystemExit(f"check-licences: {project} exists but uv is not on PATH")
    export = subprocess.run(
        [uv, "export", "--frozen", "--no-dev", "--no-emit-project", "--no-hashes", "--directory", str(ROOT / project)],
        capture_output=True, text=True, check=True,
    )
    out = subprocess.run([str(tool), "--format=json", "--with-system", "--from=mixed"],
                         capture_output=True, text=True, check=True)
    report = json.loads(out.stdout)
    reqs, problems = runtime_requirements(export.stdout)
    if problems:
        raise SystemExit(f"check-licences: {project}: " + "; ".join(problems))
    installed = [(d["Name"], d["Version"], d["License"]) for d in report]
    present = {(norm(n), v) for n, v, _ in installed}
    markers = sorted({r.marker for r in reqs if r.marker and (r.name, r.version) not in present})
    deps = bundled(installed, reqs, project, elsewhere, evaluate_markers(project, markers), used)
    if into is not None:
        # The venv's own interpreter reads its distributions; -I keeps the caller's environment and cwd out.
        read = subprocess.run([str(ROOT / project / ".venv/bin/python"), "-I", str(Path(__file__).resolve()),
                               "--read-texts"], capture_output=True, text=True, check=True)
        into.update(bundled_texts(deps, json.loads(read.stdout), project))
    return deps


# A licence or notice file by its name (pip-licenses' patterns, and the British spelling).
LICENCE_FILE = re.compile(r"(licen[cs]e|copying|notice)", re.IGNORECASE)


def read_texts(paths: list[str] | None = None) -> list[dict]:
    """Every installed distribution (in `paths`, or this interpreter's) with its licence and notice texts: each file its
    metadata declares (`License-File`: under the dist-info's `licenses/` folder, or beside METADATA before PEP 639),
    and each file its RECORD lists in a `licenses/` folder of the dist-info or under a name that starts with LICENSE,
    LICENCE, COPYING or NOTICE, anywhere in the distribution. A declared or listed file that cannot be read is named in
    `unreadable`. Identical texts are kept once."""
    from importlib import metadata

    found = []
    for dist in metadata.distributions(**({"path": paths} if paths is not None else {})):
        texts: list[str] = []
        unreadable: list[str] = []

        def add(label: str, text: str | None) -> None:
            if text is None:
                unreadable.append(label)
            elif text not in texts:
                texts.append(text)

        for declared in dist.metadata.get_all("License-File") or []:
            text = dist.read_text(f"licenses/{declared}")
            add(declared, text if text is not None else dist.read_text(declared))
        # RECORD itself, not `dist.files`, which drops listed files that are missing (Python 3.12+).
        record = dist.read_text("RECORD")
        listed = [row[0] for row in csv.reader(record.splitlines()) if row] if record is not None else \
            [str(f) for f in dist.files or []]
        for entry in listed:
            parts = PurePosixPath(entry).parts
            in_licences = len(parts) > 2 and parts[0].endswith(".dist-info") and parts[1] == "licenses"
            if in_licences or LICENCE_FILE.match(parts[-1] if parts else ""):
                try:
                    add(entry, Path(str(dist.locate_file(entry))).read_bytes().decode("utf-8", "replace"))
                except OSError:
                    add(entry, None)
        found.append({"name": dist.metadata["Name"], "version": dist.version, "texts": texts, "unreadable": unreadable})
    return found


def bundled_texts(deps: list[tuple[str, str, str]], read: list[dict], project: str) -> dict[str, str]:
    """normalized name -> the licence and notice texts of each bundled package, from `read_texts` output for its exact
    version. A bundled package the reader did not see at that version gets no entry (its text was not read); one with
    an unreadable licence file stops the check."""
    out: dict[str, str] = {}
    for name, version, _ in deps:
        seen = [d for d in read if norm(d["name"]) == norm(name) and d["version"] == version]
        lost = [f for d in seen for f in d["unreadable"]]
        if lost:
            raise SystemExit(f"check-licences: {project}: {name} {version}: licence files cannot be read: "
                             f"{', '.join(lost)}")
        if seen:
            out[norm(name)] = "\n".join(t for d in seen for t in d["texts"])
    return out


def rust_from_metadata(meta: dict) -> list[tuple[str, str, str]]:
    """(name, version, licence) of every crate the shell ships: reached from the root through edges that are
    normal dependencies on at least one target. Build and dev dependencies (and what only they pull in) do not
    ship. Cargo's deprecated `/` separator means OR. A missing licence field is UNKNOWN (refused)."""
    packages = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    root = meta["resolve"]["root"]
    seen: set[str] = set()
    stack = [root]
    while stack:
        for dep in nodes[stack.pop()]["deps"]:
            if any(k["kind"] is None for k in dep["dep_kinds"]) and dep["pkg"] not in seen:
                seen.add(dep["pkg"])
                stack.append(dep["pkg"])
    out = []
    for pid in seen:
        p = packages[pid]
        lic = p.get("license") or "UNKNOWN"
        out.append((p["name"], p["version"], " OR ".join(part.strip() for part in lic.split("/"))))
    return out


