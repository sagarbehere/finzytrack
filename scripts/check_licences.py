def js_from_report(report: dict[str, dict], own: str) -> list[tuple[str, str, str]]:
    """(name, version, licence) per package of a license-checker report, without the app's own package."""
    deps = []
    for key, info in report.items():
        name, _, version = key.rpartition("@")
        if name == own:
            continue
        lic = info.get("licenses", "UNKNOWN")
        deps.append((name, version, lic if isinstance(lic, str) else " OR ".join(lic)))
    return deps


REFUSED, PENDING, ALLOWED = 0, 1, 2


def judge(expression: str, allowed: set[str], pending: set[str]) -> int:
    """Judge an SPDX licence expression: `OR` takes its best part, `AND` its worst, `A WITH B` is one
    licence. Parentheses group. Anything that does not parse (or a classifier name such as "BSD License",
    which is not an SPDX id) is refused: the check fails closed."""
    tokens = expression.replace("(", " ( ").replace(")", " ) ").split()
    pos = 0

    def peek() -> str | None:
        return tokens[pos] if pos < len(tokens) else None

    def take() -> str:
        nonlocal pos
        pos += 1
        return tokens[pos - 1]

    def term() -> str:
        words = []
        while peek() not in (None, "AND", "OR", "WITH", "(", ")"):
            words.append(take())
        if not words:
            raise ValueError("licence term expected")
        return " ".join(words)

    def atom() -> int:
        if peek() == "(":
            take()
            value = disjunction()
            if peek() != ")":
                raise ValueError("unbalanced parentheses")
            take()
            return value
        name = term()
        if peek() == "WITH":
            take()
            name = f"{name} WITH {term()}"
        return ALLOWED if name in allowed else PENDING if name in pending else REFUSED

    def conjunction() -> int:
        value = atom()
        while peek() == "AND":
            take()
            value = min(value, atom())
        return value

    def disjunction() -> int:
        value = conjunction()
        while peek() == "OR":
            take()
            value = max(value, conjunction())
        return value

    try:
        value = disjunction()
    except ValueError:
        return REFUSED
    return value if pos == len(tokens) else REFUSED


@dataclass(frozen=True)
class Policy:
    """How one group is judged: allowed and pending licences, and reviewed packages (normalized name -> the exact
    licence expression that was reviewed; such a package passes with a warning, pending legal advice)."""

    allowed: frozenset[str]
    pending: frozenset[str]
    reviewed: dict[str, str] = field(default_factory=dict)


@dataclass(frozen=True)
class Reviewed:
    """A reviewed SPDX id for one exact version of a package whose tool-reported licence is not SPDX (BL-0050)."""

    version: str
    spdx: str
    source: str


@dataclass(frozen=True)
class Acknowledgment:
    """The acknowledgment one exact version of a package's licence requires every redistribution to keep (S0037)."""

    version: str
    text: str
    source: str


@dataclass(frozen=True)
class Textless:
    """One exact version of a package whose distribution ships no licence or notice text, and why it may still ship
    (where its licence was read instead; verifier S0037 F1)."""

    version: str
    reason: str


@dataclass(frozen=True)
class Config:
    allowed: frozenset[str]
    pending: frozenset[str]
    engine: Policy
    mapping: dict[str, Reviewed]
    acknowledgments: dict[str, Acknowledgment] = field(default_factory=dict)
    textless: dict[str, Textless] = field(default_factory=dict)
    elsewhere: dict[str, Elsewhere] = field(default_factory=dict)


ENGINE_GROUP = "Python (ledger engine)"
BACKEND_GROUP = "Python (backend sidecar)"


def load_config(path: Path) -> Config:
    """licences.allow.toml. A malformed `[mapping]` entry (no version, SPDX id or source) stops the check."""
    with path.open("rb") as fh:
        cfg = tomllib.load(fh)
    engine = cfg.get("engine", {})
    mapping: dict[str, Reviewed] = {}
    for name, entry in cfg.get("mapping", {}).items():
        if not all(isinstance(entry.get(k), str) and entry[k].strip() for k in ("version", "spdx", "source")):
            raise SystemExit(f"check-licences: [mapping.{name}] needs version, spdx and source (where it was read)")
        mapping[norm(name)] = Reviewed(entry["version"], entry["spdx"], entry["source"])
    acks: dict[str, Acknowledgment] = {}
    for name, entry in cfg.get("acknowledgment", {}).items():
        if not all(isinstance(entry.get(k), str) and entry[k].strip() for k in ("version", "text", "source")):
            raise SystemExit(f"check-licences: [acknowledgment.{name}] needs version, text and source (where it was read)")
        acks[norm(name)] = Acknowledgment(entry["version"], entry["text"], entry["source"])
    textless: dict[str, Textless] = {}
    for name, entry in cfg.get("no_licence_text", {}).items():
        if not all(isinstance(entry.get(k), str) and entry[k].strip() for k in ("version", "reason")):
            raise SystemExit(f"check-licences: [no_licence_text.{name}] needs version and reason")
        textless[norm(name)] = Textless(entry["version"], entry["reason"])
    elsewhere: dict[str, Elsewhere] = {}
    for name, entry in cfg.get("other_platform", {}).items():
        if not all(isinstance(entry.get(k), str) and entry[k].strip() for k in ("version", "spdx", "source")) \
                or not isinstance(entry.get("acknowledgment"), str):
            raise SystemExit(f"check-licences: [other_platform.{name}] needs version, spdx, source (where its licence "
                             "was read) and acknowledgment (\"\" for none)")
        elsewhere[norm(name)] = Elsewhere(entry["version"], entry["spdx"], entry["source"], entry["acknowledgment"])
    return Config(
        allowed=frozenset(cfg["allowed"]),
        pending=frozenset(cfg.get("pending_legal_advice", {})),
        engine=Policy(frozenset(engine.get("allowed", [])), frozenset(),
                      {norm(n): e for n, e in engine.get("reviewed", {}).items()}),
        mapping=mapping,
        acknowledgments=acks,
        textless=textless,
        elsewhere=elsewhere,
    )


def apply_mapping(
    deps: list[tuple[str, str, str]], mapping: dict[str, Reviewed]
) -> tuple[list[tuple[str, str, str]], list[str]]:
    """Replace a reported licence by its reviewed SPDX id when the mapping is for this exact version; a mapping
    for another version is a problem (the licence may have changed), and the reported licence stays."""
    out, problems = [], []
    for name, version, lic in deps:
        entry = mapping.get(norm(name))
        if entry is None:
            out.append((name, version, lic))
        elif entry.version != version:
            problems.append(f"{name} {version}: the reviewed licence mapping is for version {entry.version}; "
                            "read the licence again and update [mapping] in licences.allow.toml")
            out.append((name, version, lic))
        else:
            out.append((name, version, entry.spdx))
    return out, problems


# An acknowledgment clause, then the sentence it requires: quoted ('...' or "...", the closing quote followed by
# a space, a line end or the text's end, so an apostrophe inside does not end it), or unquoted up to the first full
# stop that ends a line (or the text) where the next line does not go on in lower case: "Foo Inc. and contributors."
# is one sentence, and so is "Foo Inc.\n and contributors.".
ACK_CLAUSE = re.compile(r"following\s+acknowledge?ment\s*:?", re.IGNORECASE)
ACK_QUOTED = re.compile(r"\s*(['\"])(.+?)\1(?=\s|$)", re.DOTALL)
ACK_SENTENCE = re.compile(r"\s*(.+?\.)(?=[ \t\r]*(?:\n(?![ \t]*[a-z])|\Z))", re.DOTALL)


def squash(text: str) -> str:
    return " ".join(text.split())


def required_acknowledgments(text: str) -> list[str | None]:
    """The sentences a licence text requires to be kept, one per clause; None for a clause whose sentence cannot be
    read (refused: nobody can say what the notices must carry)."""
    out: list[str | None] = []
    for clause in ACK_CLAUSE.finditer(text):
        rest = text[clause.end():]
        quoted = ACK_QUOTED.match(rest)
        sentence = quoted.group(2) if quoted else (m.group(1) if (m := ACK_SENTENCE.match(rest)) else None)
        out.append(squash(sentence) if sentence else None)
    return out


def acknowledgments(
    groups: dict[str, list[tuple[str, str, str]] | None], texts: dict[str, dict[str, str]],
    configured: dict[str, Acknowledgment], textless: dict[str, Textless] | None = None,
    elsewhere: dict[str, Elsewhere] | None = None,
) -> tuple[list[str], dict[tuple[str, str], str]]:
    """(problems, notes) for the groups whose licence texts were read (`texts`: group -> normalized name -> text),
    each package judged in its own group with that group's text and version: its text was read; it is not empty, or
    `textless` names its exact version; every acknowledgment it requires is the text of a configured entry for its
    exact version. Every configured and `textless` entry names a bundled package. `notes` ((group, normalized name) ->
    text) are what the notices carry."""
    textless = textless or {}
    problems: list[str] = []
    notes: dict[tuple[str, str], str] = {}
    seen: set[str] = set()
    for group, group_texts in texts.items():
        for name, version, _ in sorted(groups.get(group) or []):
            key = norm(name)
            seen.add(key)
            entry, empty = configured.get(key), textless.get(key)
            text = group_texts.get(key)
            other = (elsewhere or {}).get(key)
            if other is not None and other.version == version:  # bundled on another OS (BL-0050); its own entry
                if other.acknowledgment.strip():
                    notes[(group, key)] = squash(other.acknowledgment)
                continue
            if text is None:
                problems.append(f"{name} {version}: its licence text was not read, so its acknowledgments cannot be "
                                "confirmed")
                continue
            if not text.strip():
                if empty is None:
                    problems.append(f"{name} {version}: its distribution ships no licence text; read its licence "
                                    "elsewhere and add [no_licence_text] in licences.allow.toml")
                elif empty.version != version:
                    problems.append(f"{name} {version}: the [no_licence_text] entry is for version {empty.version}; "
                                    "read the licence again and update it")
                if entry is not None:
                    problems.append(f"{name} {version}: it ships no licence text, so its acknowledgment cannot be "
                                    "confirmed")
                continue
            if empty is not None:
                problems.append(f"{name} {version}: it ships a licence text now; remove its [no_licence_text] entry")
            required = required_acknowledgments(text)
            if entry is None:
                if required:
                    problems.append(f"{name} {version}: its licence requires an acknowledgment in every "
                                    "redistribution; add it to [acknowledgment] in licences.allow.toml")
            elif entry.version != version:
                problems.append(f"{name} {version}: the acknowledgment entry is for version {entry.version}; read the "
                                "licence again and update [acknowledgment] in licences.allow.toml")
            elif not required or any(r != squash(entry.text) for r in required):
                problems.append(f"{name} {version}: the configured acknowledgment is not the sentence its licence "
                                "requires")
            else:
                notes[(group, key)] = squash(entry.text)
    for key in sorted(configured.keys() - seen):
        problems.append(f"{key}: [acknowledgment] names a package that is not bundled; remove the entry")
    for key in sorted(textless.keys() - seen):
        problems.append(f"{key}: [no_licence_text] names a package that is not bundled; remove the entry")
    return problems, notes


def evaluate(
    groups: dict[str, list[tuple[str, str, str]] | None], allowed: set[str], pending: set[str],
    overrides: dict[str, Policy] | None = None, notes: dict[tuple[str, str], str] | None = None,
) -> tuple[list[str], list[str], str]:
    """(problems, warnings, notices text), each dependency judged by `judge` under its group's policy: the shared
    `allowed`/`pending`, or the group's entry in `overrides`. `notes` ((group, normalized name) -> acknowledgment)
    are written under the package's line in that group."""
    problems, warnings, lines = [], [], [HEADER]
    shared = Policy(frozenset(allowed), frozenset(pending))
    for title, deps in groups.items():
        policy = (overrides or {}).get(title, shared)
        lines.append(f"\n== {title} ==\n")
        if deps is None:
            lines.append("(package not present yet)\n")
            continue
        if not deps:
            lines.append("(no bundled dependencies)\n")
        for name, version, lic in sorted(deps):
            if policy.reviewed.get(norm(name)) == lic:
                warnings.append(f"{name} {version}: {lic} (reviewed engine dependency, ADR-0054; pending legal advice)")
            else:
                verdict = judge(lic, set(policy.allowed), set(policy.pending))
                if verdict == PENDING:
                    warnings.append(f"{name} {version}: {lic} (pending legal advice)")
                elif verdict == REFUSED:
                    where = " of the ledger engine (ADR-0054)" if policy is not shared else ""
                    problems.append(f"{name} {version}: licence {lic!r} is not on the allowlist{where}")
            lines.append(f"{name} {version}  {lic}\n")
            if (title, norm(name)) in (notes or {}):
                lines.append(f"  Acknowledgment: {(notes or {})[(title, norm(name))]}\n")
    return problems, warnings, "".join(lines)


def main(argv: list[str]) -> int:
    if argv[:1] == ["--read-texts"]:
        print(json.dumps(read_texts(argv[1:] or None)))
        return 0
    if argv[:1] == ["--eval-markers"]:  # inside a venv: packaging's marker evaluation for its interpreter
        from packaging.markers import Marker

        print(json.dumps({m: Marker(m).evaluate() for m in json.loads(sys.stdin.read())}))
        return 0
    cfg = load_config(ROOT / "licences.allow.toml")
    mapping_problems: list[str] = []

    def mapped(deps: list[tuple[str, str, str]] | None) -> list[tuple[str, str, str]] | None:
        if deps is None:
            return None
        out, problems = apply_mapping(deps, cfg.mapping)
        mapping_problems.extend(problems)
        return out

    # Licence texts per Python process: a package may be bundled in both at different versions (verifier S0037 F2).
    texts: dict[str, dict[str, str]] = {BACKEND_GROUP: {}, ENGINE_GROUP: {}}
    used: set[str] = set()
    groups = {"Python runtime (python-build-standalone)": runtime_deps(),
              BACKEND_GROUP: mapped(python_deps("backend", texts[BACKEND_GROUP], cfg.elsewhere, used)),
              ENGINE_GROUP: mapped(python_deps("engine", texts[ENGINE_GROUP], cfg.elsewhere, used)),
              "JavaScript (frontend)": js_deps(), "Rust (desktop shell)": rust_deps()}
    ack_problems, notes = acknowledgments(groups, texts, cfg.acknowledgments, cfg.textless, cfg.elsewhere)
    problems, warnings, text = evaluate(groups, set(cfg.allowed), set(cfg.pending), {ENGINE_GROUP: cfg.engine}, notes)
    problems = mapping_problems + ack_problems + stale_elsewhere(cfg.elsewhere, used) + problems
    if "--write-notices" in argv:
        NOTICES.write_text(text, encoding="utf-8")
    elif not NOTICES.exists() or NOTICES.read_text(encoding="utf-8") != text:
        problems.append("THIRD_PARTY_NOTICES is stale; run python3 scripts/check_licences.py --write-notices")
    for w in warnings:
        print(f"check-licences: warning: {w}", file=sys.stderr)
    for p in problems:
        print(f"check-licences: {p}", file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
