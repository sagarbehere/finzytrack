#!/usr/bin/env python3
"""Generate design/specs/write-path/intent-table.md (the per-mutator intended-change table) from its TOML source.

Usage: python3 scripts/gen_intent_table.py            # write the markdown
       python3 scripts/gen_intent_table.py --stdout   # print it (used by check_generated.py)
"""

from __future__ import annotations

import sys
import tomllib
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "design/specs/write-path/intent-table.toml"
TARGET = ROOT / "design/specs/write-path/intent-table.md"
HEADER = "<!-- GENERATED by scripts/gen_intent_table.py from design/specs/write-path/intent-table.toml. Do not edit. -->"


def cell(value: object) -> str:
    if isinstance(value, list):
        text = "; ".join(str(v) for v in value) if value else "—"
    else:
        text = str(value) if value else "—"
    return text.replace("|", "\\|").replace("\n", " ")


def render(table: dict) -> str:
    rows = table["mutator"]
    out = [HEADER, "", "# Per-mutator intended-change table", ""]
    out.append("What each ledger-writing mutator may change. Column meanings and rules: [README.md](README.md). "
               "Edit `intent-table.toml`, then run `python3 scripts/gen_intent_table.py`.")
    out.append("")
    status = Counter(r["status"].split(":")[0] for r in rows)
    kinds = Counter(r["kind"] for r in rows)
    out.append(f"{len(rows)} mutators: " + ", ".join(f"{n} {k}" for k, n in sorted(status.items()))
               + "; kinds " + ", ".join(f"{n} {k}" for k, n in sorted(kinds.items()))
               + f"; {sum(r['old'].startswith('n/a') for r in rows)} with no old-app counterpart.")
    out.append("")
    out.append("## Summary")
    out.append("")
    out.append("| Mutator | Kind | Old endpoint | Edits | Status | Milestone |")
    out.append("|---|---|---|---|---|---|")
    for r in rows:
        out.append(f"| `{r['id']}` | {r['kind']} | {cell(r['old'])} | {cell(r['edits'])} | {cell(r['status'])} | {r['milestone']} |")
    out.append("")
    out.append("## Rows")
    for r in rows:
        out.append("")
        out.append(f"### `{r['id']}`")
        out.append("")
        for label, key in (("Capabilities", "caps"), ("Kind of edit", "kind"), ("Old endpoint", "old"), ("Edits", "edits"),
                           ("Files", "files"), ("Intended change", "intent"), ("Metadata written", "meta"),
                           ("The preview may list (never a refusal, ADR-0067)", "ack"), ("Refused when", "refuses"), ("v0.3 oracle expectation", "oracle"),
                           ("Status", "status"), ("Milestone", "milestone"), ("ADRs", "adrs")):
            out.append(f"- **{label}:** {cell(r[key])}")
    out.append("")
    out.append("## Legacy mutators")
    out.append("")
    out.append("| v0.3 `LedgerManager` method | v0.4 row(s) |")
    out.append("|---|---|")
    for name in table["legacy"]["mutators"]:
        out.append(f"| `{name}` | {cell(table['legacy']['map'][name])} |")
    return "\n".join(out) + "\n"


def main() -> int:
    with SOURCE.open("rb") as f:
        text = render(tomllib.load(f))
    if "--stdout" in sys.argv:
        sys.stdout.write(text)
    else:
        TARGET.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
