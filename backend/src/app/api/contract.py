"""The offline OpenAPI export and the contract's own rules (ADR-0038 and its amendment; ARCHITECTURE.md §4.1).

`export_openapi()` builds the app with a container factory that is never called (building an app does no I/O) and
returns its OpenAPI document; no server starts. `render` writes it as `contracts/openapi.json` does: sorted keys, two
spaces, the GENERATED header as the first key (`scripts/check_generated.py`). `contract_problems` holds a document to
the rules the generated client relies on: every operation declares its scope and writes; every operation answers
errors with the error envelope (`default` and every other non-2xx answer it declares) and success inside
`{data, meta}`; every field of a response is required;
every path parameter is declared; no FastAPI default error schema and no separate input and output schemas.
"""

from __future__ import annotations

import json
import re
from collections.abc import Iterator
from typing import Any, cast

from app.api.app import create_app
from app.api.container import ApiContainer

HEADER = (
    "GENERATED by backend/scripts/export_openapi.py from the app (app.api.create_app). Do not edit: change the"
    " backend and export again; the frontend's types are generated from this file (ADR-0038)."
)
ERROR_ENVELOPE = "#/components/schemas/ErrorEnvelope"
FORBIDDEN_SCHEMAS = ("HTTPValidationError", "ValidationError")
PATH_PARAM = re.compile(r"\{([^}]+)\}")


class ExportServesNoRequest(RuntimeError):
    """The export's container factory was called: building the app must not serve or resolve anything."""


def _no_container() -> ApiContainer:
    raise ExportServesNoRequest


def export_openapi() -> dict[str, Any]:
    return create_app(_no_container).openapi()


def render(doc: dict[str, Any]) -> str:
    return json.dumps({"$comment": HEADER, **doc}, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def contract_problems(doc: dict[str, Any]) -> list[str]:
    schemas: dict[str, Any] = doc.get("components", {}).get("schemas", {})
    out: list[str] = []
    out.extend(
        f"{name}: FastAPI's default error schema; every error is the envelope"
        for name in FORBIDDEN_SCHEMAS
        if name in schemas
    )
    out.extend(
        f"{name}: a separate input or output schema (one schema per model, ADR-0038 amendment)"
        for name in schemas
        if name.endswith(("-Input", "-Output"))
    )
    roots: list[str] = []
    for path, item in doc.get("paths", {}).items():
        for method, op in item.items():
            where = f"{method.upper()} {path}"
            out.extend(f"{where}: no {key}" for key in ("x-ft-scope", "x-ft-writes") if key not in op)
            declared = {p.get("name") for p in op.get("parameters", []) if p.get("in") == "path"}
            out.extend(
                f"{where}: path parameter {{{name}}} is not declared (the client builds the address from it)"
                for name in PATH_PARAM.findall(path)
                if name not in declared
            )
            responses: dict[str, Any] = op.get("responses", {})
            if "default" not in responses:
                out.append(f"{where}: no default answer; it must be the error envelope")
            for status, answer in responses.items():
                ref = _ref(answer)
                if ref is not None:
                    roots.append(ref)
                if status.startswith("2"):
                    if not _is_envelope(schemas, ref):
                        out.append(f"{where}: its {status} answer is not in the envelope {{data, meta}}")
                elif ref != ERROR_ENVELOPE:
                    out.append(f"{where}: its {status} answer must be the error envelope")
    out.extend(_optional_fields(schemas, roots))
    return out


def _ref(answer: Any) -> str | None:
    """The `$ref` of an answer's JSON schema, if it has one."""
    node: object = answer
    for key in ("content", "application/json", "schema", "$ref"):
        node = _get(node, key)
    return node if isinstance(node, str) else None


def _get(node: object, key: str) -> object:
    return cast("dict[str, object]", node).get(key) if isinstance(node, dict) else None


def _is_envelope(schemas: dict[str, Any], ref: str | None) -> bool:
    properties = _get(schemas.get(ref.rsplit("/", 1)[-1]) if ref else None, "properties")
    return isinstance(properties, dict) and set(cast("dict[str, object]", properties)) == {"data", "meta"}


def _optional_fields(schemas: dict[str, Any], roots: list[str]) -> Iterator[str]:
    """Every property of every schema reachable from an answer is required (ADR-0038 amendment)."""
    seen: set[str] = set()
    todo = [r.rsplit("/", 1)[-1] for r in roots]
    while todo:
        name = todo.pop()
        if name in seen or name not in schemas:
            continue
        seen.add(name)
        schema = schemas[name]
        required = set(schema.get("required", []))
        for prop in schema.get("properties", {}):
            if prop not in required:
                yield f"{name}.{prop}: a response field must be required (no server-side defaults)"
        todo.extend(ref.rsplit("/", 1)[-1] for ref in _refs(schema))


def _refs(node: Any) -> Iterator[str]:
    if isinstance(node, dict):
        for key, value in node.items():  # pyright: ignore[reportUnknownVariableType]
            if key == "$ref" and isinstance(value, str):
                yield value
            else:
                yield from _refs(value)
    elif isinstance(node, list):
        for value in node:  # pyright: ignore[reportUnknownVariableType]
            yield from _refs(value)
