#!/usr/bin/env python3
"""Generate the reference of the backend statecharts from their tables (S0040; EP-20; ARCHITECTURE.md §7).

usage (from the repo root): backend/.venv/bin/python -I backend/scripts/gen_statecharts.py [--stdout]

Writes `design/generated/statecharts/engine-supervision.md` (with `--stdout`, prints it instead): the states and
events with their docstrings, a Mermaid diagram and the table row by row, all read from
`app.platform.engine_supervision.ROWS`. `scripts/check_generated.py` runs it with `--stdout` and fails when the
committed file differs.
"""

from __future__ import annotations

import sys
from pathlib import Path

from app.platform.engine_supervision import EVENTS, RESTING, STATES, rules

OUT = Path(__file__).resolve().parents[2] / "design" / "generated" / "statecharts" / "engine-supervision.md"

HEADER = (
    "<!-- GENERATED by backend/scripts/gen_statecharts.py from backend/src/app/platform/engine_supervision.py."
    " Do not edit. -->"
)


def summary(cls: type) -> str:
    doc = (cls.__doc__ or "").strip()
    return " ".join(doc.split("\n\n")[0].split())


def render() -> str:
    resting = (s.__name__ for s in RESTING)
    out = [
        HEADER,
        "",
        "# Engine supervision statechart",
        "",
        "The ledger engine's lifecycle as the main sidecar supervises it: `app.platform.engine_supervision.transition`"
        " over `ROWS`, driven by `app.platform.adapters.engine_client.EngineClient` (ARCHITECTURE.md §2.0, §7)."
        " A pair that is not listed raises `IllegalTransition`. Resting states (" + ", ".join(resting) + ") are"
        " where a public call can find the client; the others pass within one call.",
        "",
        "## States",
        "",
        "| State | Meaning |",
        "|---|---|",
        *(f"| `{s.__name__}` | {summary(s)} |" for s in STATES),
        "",
        "## Events",
        "",
        "| Event | Meaning |",
        "|---|---|",
        *(f"| `{e.__name__}` | {summary(e)} |" for e in EVENTS),
        "",
        "## Diagram",
        "",
        "```mermaid",
        "stateDiagram-v2",
        "    [*] --> Idle",
    ]
    for rule in rules():
        out.extend(f"    {rule.state.__name__} --> {t.__name__}: {rule.event.__name__}" for t in rule.targets)
    out += [
        "```",
        "",
        "## Transitions",
        "",
        "| From | Event | To | Effects | Note |",
        "|---|---|---|---|---|",
    ]
    for rule in rules():
        targets = ", ".join(f"`{t.__name__}`" for t in rule.targets)
        effects = ", ".join(f"`{e.__name__}`" for e in rule.effects) or "none"
        out.append(f"| `{rule.state.__name__}` | `{rule.event.__name__}` | {targets} | {effects} | {rule.note} |")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    if sys.argv[1:] == ["--stdout"]:
        sys.stdout.write(render())
    elif not sys.argv[1:]:
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text(render(), encoding="utf-8")
    else:
        sys.exit("usage: gen_statecharts.py [--stdout]")
