#!/usr/bin/env python3
"""Export the workspace manifest's JSON Schema (EP-14, EP-16; S0051).

usage (from the repo root): backend/.venv/bin/python -I backend/scripts/export_manifest_schema.py [--stdout]

Writes `contracts/workspace-manifest.schema.json` from `app.workspaces.format.manifest.ManifestV1` (with `--stdout`,
prints it instead). `scripts/check_generated.py` runs it with `--stdout` and fails when the committed file differs.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from app.workspaces.format.manifest import ManifestV1

OUT = Path(__file__).resolve().parents[2] / "contracts" / "workspace-manifest.schema.json"
HEADER = (
    "GENERATED by backend/scripts/export_manifest_schema.py from app.workspaces.format.manifest.ManifestV1. "
    "Do not edit: change the model and export again (EP-16)."
)


def render() -> str:
    schema = ManifestV1.model_json_schema()
    doc = {"$comment": HEADER, "$schema": "https://json-schema.org/draft/2020-12/schema", **schema}
    return json.dumps(doc, indent=2, ensure_ascii=False) + "\n"


def main(argv: list[str]) -> int:
    text = render()
    if "--stdout" in argv:
        sys.stdout.write(text)
    else:
        OUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
