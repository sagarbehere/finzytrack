def _code_text(code: ErrorCode) -> str:
    spec = spec_for(code)
    if spec is None:  # every code in CODES is registered (a test holds ErrorCode and the registry equal)
        raise KeyError(code)
    return f"**Message:** {spec.message} **Next step:** {spec.next_step}"


