def _code_text(code: ErrorCode) -> str:
    spec = spec_for(code)
    if spec is None:  # every code in CODES is registered (a test holds ErrorCode and the registry equal)
        raise KeyError(code)
    return f"**Message:** {spec.message} **Next step:** {spec.next_step}"


REGISTRY: tuple[Row, ...] = tuple(
    (f"msg:code.{code.value}", f"`{code.value}`: the registry's message and next step", lambda c=code: _code_text(c))
    for code in CODES
)


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _table(rows: tuple[Row, ...]) -> list[str]:
    out = ["| Key | Where it shows | Text |", "|---|---|---|"]
    out += [f"| `{key}` | {where} | {_cell(make())} |" for key, where, make in rows]
    return out


def _check_complete() -> None:
    not_saved = set(get_args(NotSavedReason.__value__)) - SAME_WORDS_AS_IO_ERROR
    blocking = set(get_args(Reason.__value__))
    missing = sorted(
        (not_saved - _seen_not_saved)
        | (blocking - _seen_blocking)
        | (set(get_args(NotCreatedReason.__value__)) - _seen_create)
    )
    if missing:
        raise SystemExit(f"gen_engine_job_texts: no row renders {', '.join(missing)}")  # noqa: TRY003


def render() -> str:
    with mock.patch.object(rt, "system_answer", return_value="<system's answer>"):
        out = [
            HEADER,
            "",
            "# Engine-job texts",
            "",
            "What the user reads about engine jobs, saves and recovery, rendered from the code that says it, with"
            " placeholders in angle brackets. `design/specs/engine-jobs.md` §11 says when each text shows, with its"
            " actions and code, and cites it by its key. To change a text, change the code and regenerate this file.",
            "",
            "## Jobs (`app.platform.engine_jobs.text`)",
            "",
            *_table(JOB),
            "",
            "## Saves (`app.platform.engine_jobs.save_text`)",
            "",
            *_table(SAVE),
            "",
            "## Recovery (`app.platform.engine_jobs.recovery_text`)",
            "",
            "Each blocked screen's actions are `Screen.actions` (§11).",
            "",
            *_table(RECOVERY),
            "",
            "## Creates (`app.platform.engine_jobs.create_text`)",
            "",
            *_table(CREATE),
            "",
            "## Error codes (`app.platform.errors.registry`)",
            "",
            "The text a save shows for a code it has no own words for (`save_text.text`), and the API's message.",
            "",
            *_table(REGISTRY),
        ]
    _check_complete()
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    if sys.argv[1:] == ["--stdout"]:
        sys.stdout.write(render())
    elif not sys.argv[1:]:
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text(render(), encoding="utf-8")
    else:
        sys.exit("usage: gen_engine_job_texts.py [--stdout]")
