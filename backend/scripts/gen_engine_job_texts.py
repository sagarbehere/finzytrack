#!/usr/bin/env python3
"""Generate the reference of what the user reads about engine jobs (S0079, BL-0192; INV-19; engine-jobs spec §11).

usage (from the repo root): backend/.venv/bin/python -I backend/scripts/gen_engine_job_texts.py [--stdout]

Writes `design/generated/engine-job-texts.md` (with `--stdout`, prints it instead): every text the sidecar's four
text modules produce (`app.platform.engine_jobs.text`, `save_text`, `recovery_text`, `create_text`) and the
registry's message and next step for the engine-job codes, rendered by calling the code with placeholders such as
`<file>` and `<workspace>`. Each text has a key (`msg:…`) that `design/specs/engine-jobs.md` cites, so each
sentence has one home, the code. `scripts/check_generated.py` runs it with `--stdout` and fails when the committed
file differs; `backend/tests/platform/test_engine_job_texts_spec.py` checks the keys both ways against the spec.

The system's own answer to an error (`recovery_text.system_answer`, `strerror`) differs by OS, so it is rendered as
`<system's answer>`.
"""

