def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _table(rows: tuple[Row, ...]) -> list[str]:
    out = ["| Key | Where it shows | Text |", "|---|---|---|"]
    out += [f"| `{key}` | {where} | {_cell(make())} |" for key, where, make in rows]
    return out


def _check_complete() -> None:
    not_saved = set(get_args(NotSavedReason.__value__)) - SAME_WORDS_AS_IO_ERROR
    blocking = set(get_args(Reason.__value__))
    missing = sorted(
        (not_saved - _seen_not_saved)
        | (blocking - _seen_blocking)
        | (set(get_args(NotCreatedReason.__value__)) - _seen_create)
        | (set(get_args(NotCopiedReason.__value__)) - _seen_copy)
    )
    if missing:
        raise SystemExit(f"gen_engine_job_texts: no row renders {', '.join(missing)}")  # noqa: TRY003


