#!/usr/bin/env python3
"""Write every TLC configuration of the mirror-publish model, and configs.txt (S0085).

Run from anywhere: python3 gen_cfgs.py (formal/tla/mirror-publish). The .cfg files and configs.txt it writes are
committed; edit this table, not the files (`--check` says whether they are in step; a meta-test runs it).

A configuration = a world (constants), the specification (Spec), the properties to check and the result it must
have. Durability only (EP-19): BL-0113's two properties, nothing else. Tiers: S (small, seconds), M, L (the owner's).
Every mutant runs on a small world and checks only the property it must break.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CFG_DIR = os.path.join(HERE, "cfg")

DEFAULTS = {
    "MUTANT": '"none"', "Readers": '{"r1"}', "OutReaders": "{}", "MaxGen": "3", "MaxBuilds": "0", "MaxReqs": "0", "MaxEdits": "0",
    "MaxCuts": "0", "MaxCrash": "0", "MaxAppCrash": "0", "MaxPower": "0", "MaxPurge": "0",
    "MayIncomplete": "FALSE",
}

# publish.md §10: the two properties of BL-0113 (state invariants)
INVARIANTS = ["ReadersSeeCompleteGeneration", "SnapshotIsSomeCommittedState"]


def S(**kw):
    return {k: (str(v).upper() if isinstance(v, bool) else str(v)) for k, v in kw.items()}


# name: (tier, world overrides)
WORLDS = {
    # publishes one after another while a reader reads twice per request; an incomplete build; an engine death
    "S_publish": ("S", S(MaxGen=4, MaxBuilds=4, MaxReqs=2, MaxCrash=1, MayIncomplete=True)),
    # a power loss at any step of a publish, then reads of what the next start finds
    "S_power": ("S", S(MaxGen=4, MaxBuilds=3, MaxReqs=2, MaxPower=1, MaxAppCrash=1, MaxCrash=1)),
    # the OS purges the cache folder under a running app and an outside tool (which outlives the app's crash)
    "S_purge": ("S", S(OutReaders='{"r1"}', MaxGen=3, MaxBuilds=2, MaxReqs=2, MaxEdits=1, MaxPurge=1,
                       MaxAppCrash=1)),
    # the ledger moves during a build: an outside editor, a save of ours cut with its `.open` journal, recovery
    "S_ledger": ("S", S(MaxGen=3, MaxBuilds=2, MaxReqs=1, MaxEdits=2, MaxCuts=1)),
    # medium and large: actors combined (the owner's runs, BL-0110's row)
    "M_all": ("M", S(MaxGen=4, MaxBuilds=3, MaxReqs=2, MaxEdits=1, MaxCuts=1, MaxCrash=1, MaxPower=1,
                     MaxPurge=1, MayIncomplete=True)),
    "L_all": ("L", S(Readers='{"r1", "r2"}', OutReaders='{"r2"}', MaxPurge=1, MaxGen=5, MaxBuilds=4, MaxReqs=2, MaxEdits=2, MaxCuts=1, MaxCrash=1,
                     MaxAppCrash=1, MaxPower=2, MayIncomplete=True)),
}

# mutant: (world it runs on, property it must break, extra overrides). MAPPING.md §4.1 says what each one breaks.
MUTANTS = [
    ("no_file_sync", "S_power", "ReadersSeeCompleteGeneration", {}),
    ("publish_incomplete", "S_publish", "ReadersSeeCompleteGeneration", {}),
    ("build_in_place", "S_publish", "ReadersSeeCompleteGeneration", {}),
    ("no_tag", "S_purge", "SnapshotIsSomeCommittedState", {}),
    ("no_recheck", "S_ledger", "SnapshotIsSomeCommittedState", {}),
    ("no_open_check", "S_ledger", "SnapshotIsSomeCommittedState", {}),
    ("reresolve_per_read", "S_ledger", "SnapshotIsSomeCommittedState", {}),
]

# witness: (the predicate whose negation a base world must reach, the world). Vacuity (MAPPING.md §4.2).
WITNESSES = [
    ("W_ReadTwice", "S_publish"),
    ("W_ReadOldAfterNew", "S_publish"),
    ("W_ReadDeleted", "S_publish"),
    ("W_IncompleteRefused", "S_publish"),
    ("W_ReadAfterPower", "S_power"),
    ("W_TornLeft", "S_power"),
    ("W_LinkReverted", "S_power"),
    ("W_ReadAcrossPurge", "S_purge"),
    ("W_OutsideAfterCrash", "S_purge"),
    ("W_MovedRefused", "S_ledger"),
    ("W_OpenRefused", "S_ledger"),
]


def render(name, consts, invariants, comment):
    lines = ["\\* generated by gen_cfgs.py: %s" % name, "\\* %s" % comment, "SPECIFICATION Spec", "CONSTANTS"]
    lines += ["    %s = %s" % (k, consts[k]) for k in DEFAULTS]
    lines += ["INVARIANT %s" % i for i in invariants]
    lines.append("CHECK_DEADLOCK FALSE")  # a world ends when its bounds are used up
    return "\n".join(lines) + "\n"


def consts_of(world, extra=None):
    consts = dict(DEFAULTS)
    consts.update(WORLDS[world][1])
    consts.update(extra or {})
    return consts


def build():
    out, rows = {}, []
    for name, (tier, _w) in WORLDS.items():
        out[name + ".cfg"] = render(name, consts_of(name), INVARIANTS, "both properties of publish.md section 10")
        rows.append((name, "PASS", tier, "base", "check"))
    for mut, base, prop, extra in MUTANTS:
        consts = consts_of(base, extra)
        consts["MUTANT"] = '"%s"' % mut
        name = "MUT_" + mut
        out[name + ".cfg"] = render(name, consts, [prop], "mutant %s on %s: TLC must report %s violated" % (mut, base, prop))
        rows.append((name, "VIOLATE:" + prop, "S", "mutant", "check"))
    for wit, base in WITNESSES:
        name = "WIT_" + wit[2:]
        out[name + ".cfg"] = render(name, consts_of(base), [wit],
                                    "witness %s on %s: TLC must report it violated (the branch is reached)" % (wit, base))
        rows.append((name, "VIOLATE:" + wit, "S", "witness", "check"))
    lst = ["# Generated by gen_cfgs.py; do not edit by hand.",
           "# <config> <expected: PASS | VIOLATE:<property>> <tier: S | M | L> <kind: base | mutant | witness> <mode: check | simulate>"]
    lst += ["%-28s %-42s %s %-7s %s" % r for r in rows]
    out["configs.txt"] = "\n".join(lst) + "\n"
    return out


def main():
    check = "--check" in sys.argv
    files = build()
    os.makedirs(CFG_DIR, exist_ok=True)
    stale = []
    for fname, text in files.items():
        path = os.path.join(HERE, fname) if fname == "configs.txt" else os.path.join(CFG_DIR, fname)
        old = open(path).read() if os.path.exists(path) else None
        if old != text:
            stale.append(fname)
            if not check:
                with open(path, "w") as f:
                    f.write(text)
    extra = sorted(set(os.listdir(CFG_DIR)) - {f for f in files if f.endswith(".cfg")})
    if check:
        if stale or extra:
            print("out of date: " + ", ".join(stale + extra))
            return 1
        print("configs up to date (%d files)" % len(files))
        return 0
    for f in extra:
        os.remove(os.path.join(CFG_DIR, f))
    print("wrote %d files (%d changed, %d removed)" % (len(files), len(stale), len(extra)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
