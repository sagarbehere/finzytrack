#!/usr/bin/env node
// Generate the API's runtime tables from the contract (ADR-0038; ARCHITECTURE.md §4.1, §6.2; S0166, BL-0107).
//
// usage (from anywhere): node frontend/scripts/gen-api-extras.mjs [--contract PATH] [--stdout keys|errors]
//
// Reads contracts/openapi.json (or PATH) and writes two files under frontend/src/api/generated/ (with --stdout,
// prints one of them instead; scripts/check_generated.py runs that and fails when the committed file differs):
//   keys.gen.ts    every operation's declared scope and writes (`x-ft-scope`, `x-ft-writes`), by path and method:
//                  the query keys are built from it (`api/keys.ts`), never by hand (ADR-0037);
//   errors.gen.ts  every error code of the registry with its class, read from the error envelope's union
//                  (`ErrorEnvelope.error`, one schema per code with `code` and `class` constants; S0046).
// Fails closed: an operation without both declarations, a scope that does not match its path (a ledger or config
// operation outside /api/w/{ws}/, an app one inside it), or an error schema without its two constants, stops the
// generator with a message instead of emitting a table that leaves it out. Not generated yet (BL-0107): the
// `x-ft-type` brands and `decode.gen.ts`.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const METHODS = ['get', 'put', 'post', 'delete', 'options', 'head', 'patch', 'trace']
const SCOPES = new Set(['app', 'ledger', 'config'])
const WRITES = new Set(['ledger', 'config', 'none'])

function fail(message) {
  process.stderr.write(`gen-api-extras: ${message}\n`)
  process.exit(1)
}

const header = (what) =>
  `// GENERATED by frontend/scripts/gen-api-extras.mjs from contracts/openapi.json (${what}). Do not edit.\n`

function keysModule(doc) {
  const lines = []
  for (const path of Object.keys(doc.paths ?? {}).sort()) {
    const item = doc.paths[path]
    const ops = []
    for (const method of METHODS) {
      const op = item[method]
      if (op === undefined) continue
      const scope = op['x-ft-scope']
      const writes = op['x-ft-writes']
      if (!SCOPES.has(scope)) fail(`${method.toUpperCase()} ${path}: x-ft-scope is ${JSON.stringify(scope)}`)
      if (!WRITES.has(writes)) fail(`${method.toUpperCase()} ${path}: x-ft-writes is ${JSON.stringify(writes)}`)
      if (scope !== 'app' && !path.startsWith('/api/w/{ws}/')) {
        fail(`${method.toUpperCase()} ${path}: a ${scope} operation must sit under /api/w/{ws}/`)
      }
      // Its key would sit outside the workspace's ['ws', ws] prefix, so a switch would not drop it.
      if (scope === 'app' && path.startsWith('/api/w/{ws}/')) {
        fail(`${method.toUpperCase()} ${path}: an app operation must not sit under /api/w/{ws}/`)
      }
      ops.push(`    ${method}: { scope: '${scope}', writes: '${writes}' },`)
    }
    lines.push(`  '${path}': {`, ...ops, '  },')
  }
  return (
    header('x-ft-scope, x-ft-writes') +
    "// Each operation's scope and writes, by path and method. Query keys come from here (src/api/keys.ts).\n" +
    'export const operations = {\n' +
    lines.join('\n') +
    (lines.length ? '\n' : '') +
    '} as const\n'
  )
}

function errorsModule(doc) {
  const schemas = doc.components?.schemas ?? {}
  const union = schemas.ErrorEnvelope?.properties?.error?.oneOf
  if (!Array.isArray(union) || union.length === 0) fail('ErrorEnvelope.error is not a union of error schemas')
  const entries = []
  for (const member of union) {
    const name = String(member.$ref ?? '').replace('#/components/schemas/', '')
    const props = schemas[name]?.properties
    const code = props?.code?.const
    const klass = props?.class?.const
    if (typeof code !== 'string' || typeof klass !== 'string')
      fail(`${name || 'an error schema'}: no code or class constant`)
    entries.push([code, klass])
  }
  entries.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
  return (
    header('ErrorEnvelope.error') +
    '// Every server error code with its class (ARCHITECTURE.md §6.1). The decoder (src/api/errors.ts) accepts only\n' +
    '// these codes, each with its own class.\n' +
    'export const serverErrorClasses = {\n' +
    entries.map(([code, klass]) => `  ${code}: '${klass}',`).join('\n') +
    '\n} as const\n'
  )
}

const args = process.argv.slice(2)
const at = args.indexOf('--contract')
const contract = at >= 0 ? args[at + 1] : fileURLToPath(new URL('../../contracts/openapi.json', import.meta.url))
if (contract === undefined) fail('--contract needs a path')
const doc = JSON.parse(readFileSync(contract, 'utf8'))
const outputs = { keys: keysModule(doc), errors: errorsModule(doc) }

const which = args.indexOf('--stdout')
if (which >= 0) {
  const name = args[which + 1]
  if (!(name in outputs)) fail('--stdout needs keys or errors')
  process.stdout.write(outputs[name])
} else {
  for (const [name, text] of Object.entries(outputs)) {
    writeFileSync(fileURLToPath(new URL(`../src/api/generated/${name}.gen.ts`, import.meta.url)), text)
  }
}
