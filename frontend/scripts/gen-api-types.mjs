#!/usr/bin/env node
// Generate the API's TypeScript types from the contract (ADR-0038; ARCHITECTURE.md §4.1; S0046).
//
// usage (from anywhere): node frontend/scripts/gen-api-types.mjs [--stdout]
//
// Reads contracts/openapi.json (exported offline by backend/scripts/export_openapi.py) and writes
// frontend/src/api/generated/openapi.ts with openapi-typescript (with --stdout, prints it instead).
// scripts/check_generated.py runs it with --stdout and fails when the committed file differs, so the contract and
// its types land in the same commit. Types only: the client (openapi-fetch), the x-ft-type brands, the decoders and
// the query keys arrive with the frontend's API foundations (BL-0107).
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

import openapiTS, { astToString } from 'openapi-typescript'

const contract = fileURLToPath(new URL('../../contracts/openapi.json', import.meta.url))
const out = fileURLToPath(new URL('../src/api/generated/openapi.ts', import.meta.url))
const header =
  '// GENERATED by frontend/scripts/gen-api-types.mjs from contracts/openapi.json (openapi-typescript). Do not edit.\n'

const doc = JSON.parse(readFileSync(contract, 'utf8'))
delete doc.$comment // the file's GENERATED header, not part of the OpenAPI document
const ast = await openapiTS(doc, { silent: true })
const text = header + astToString(ast)

if (process.argv.includes('--stdout')) {
  process.stdout.write(text)
} else {
  writeFileSync(out, text)
}
